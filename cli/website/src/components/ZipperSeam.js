/** Group the uncovered points into N equal-count radial cohorts so the ember
 *  "flush" is N group tweens sweeping outward — never per-dot scrub tweens. */
function monolithCohorts(mono, nCohorts = 8) {
  if (!mono || !Array.isArray(mono.pts) || !mono.pts.length) return null;
  const cx = mono.box[0] / 2;
  const cy = mono.box[1] / 2;
  const covered = [];
  const uncovered = [];
  for (const p of mono.pts) (p[2] ? covered : uncovered).push(p);
  const withD = uncovered
    .map((p) => ({p, d: Math.hypot(p[0] - cx, p[1] - cy)}))
    .sort((a, b) => a.d - b.d);
  const cohorts = Array.from({length: nCohorts}, () => []);
  withD.forEach((e, i) => {
    cohorts[Math.min(nCohorts - 1, Math.floor((i * nCohorts) / withD.length))].push(e.p);
  });
  return {covered, cohorts};
}
