function computeFieldMesh(cov) {
  const edges = [];
  const seen = new Set();
  const step = Math.max(1, Math.floor(cov.length / 110));
  for (let a = 0; a < cov.length && edges.length < 150; a += step) {
    let best = -1;
    let bd = Infinity;
    for (let b = 0; b < cov.length; b += 1) {
      if (b === a) continue;
      const dx = cov[a][0] - cov[b][0];
      const dy = cov[a][1] - cov[b][1];
      const d = dx * dx + dy * dy;
      if (d < bd) {
        bd = d;
        best = b;
      }
    }
    if (best >= 0) {
      const k = a < best ? `${a}-${best}` : `${best}-${a}`;
      if (!seen.has(k)) {
        seen.add(k);
        edges.push([a, best]);
      }
    }
  }
  return edges;
}
