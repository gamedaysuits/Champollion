#!/usr/bin/env node
/**
 * build-rails-data.mjs — the facts the rails pages show that live in the
 * tools, not in the recording: written to src/data/rails-demo/site-data.json.
 *
 *   anatomy  — the project's folders and what goes in each: the "Where things
 *              go" table of shared/templates/language/README.md, the README
 *              `champollion new` writes into every project.
 *   stages   — the rails' stages: shared/journeys/language.json.
 *   choices  — what a file's holders decide: the set/1 schema's own
 *              descriptions (shared/schemas/framework/set.v1.schema.json).
 *   tiers    — how a test set may be registered with the network:
 *              EXPOSURE_TIERS in cli/lib/corpus-registration.mjs.
 *   licences — each package's licence: cli/package.json,
 *              mcp-server/package.json, forge/pyproject.toml,
 *              arena/pyproject.toml.
 *   requirements — what the CLI needs to run: cli/package.json engines.
 *
 * A page that showed any of these by hand would drift the day the tools
 * changed. So the file is generated, committed, and checked: `--check` (run
 * by the site's prebuild and by cli/test/website-rails-data.test.js) fails
 * when the tools say something the committed file does not.
 *
 * Usage:  node scripts/build-rails-data.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(SITE, '..', '..');
const OUT = path.join(SITE, 'src', 'data', 'rails-demo', 'site-data.json');
const read = (rel) => fs.readFileSync(path.join(REPO, rel), 'utf-8');

function die(msg) {
  console.error(`[build-rails-data] ${msg}`);
  process.exit(1);
}

function anatomy() {
  const md = read('shared/templates/language/README.md');
  const sec = md.split('## Where things go')[1];
  if (!sec) die('shared/templates/language/README.md has no "Where things go" section');
  const rows = [];
  for (const line of sec.split('\n')) {
    const m = /^\|\s*`([^`]+)`\s*\|\s*(.+?)\s*\|\s*$/.exec(line);
    if (m) rows.push({folder: m[1], holds: m[2].replace(/`/g, '')});
    if (rows.length && line.startsWith('## ')) break;
  }
  if (rows.length < 5) die('the template README\'s folder table has fewer than 5 rows — read it again');
  const sidecar = /Beside each data file, ([\s\S]+?)\n\n/.exec(sec);
  if (!sidecar) die('the template README no longer explains the sidecar');
  return {rows, sidecar: `Beside each data file, ${sidecar[1].replace(/\s*\n\s*/g, ' ').replace(/`/g, '')}`};
}

function stages() {
  const j = JSON.parse(read('shared/journeys/language.json'));
  const out = (j.stages || []).map((s, i) => ({n: i + 1, id: s.id, title: s.title || s.name}));
  if (out.length === 0 || out.some((s) => !s.title)) die('shared/journeys/language.json stages have no titles');
  return out;
}

function choices() {
  const s = JSON.parse(read('shared/schemas/framework/set.v1.schema.json'));
  const p = s.properties || {};
  const tx = p.transmission;
  const tr = p.terms && p.terms.properties && p.terms.properties.training;
  if (!tx || !tr) die('set.v1 schema has no transmission / terms.training');
  return {
    transmission: {values: tx.enum, description: tx.description},
    training: {values: tr.enum, description: tr.description},
  };
}

async function tiers() {
  const mod = await import(pathToFileURL(path.join(REPO, 'cli', 'lib', 'corpus-registration.mjs')).href);
  if (!Array.isArray(mod.EXPOSURE_TIERS)) die('EXPOSURE_TIERS not exported');
  return mod.EXPOSURE_TIERS.map((t) => ({
    key: t.key, label: t.label, explanation: t.explanation,
    registers: t.registers, uploadsContent: t.uploadsContent, uploadsCiphertext: t.uploadsCiphertext,
    default: t.key === mod.DEFAULT_TIER,
  }));
}

function licences() {
  const npm = (rel) => JSON.parse(read(rel));
  const toml = (rel) => {
    const t = read(rel);
    const name = /^name\s*=\s*"([^"]+)"/m.exec(t);
    const lic = /^license\s*=\s*"([^"]+)"/m.exec(t);
    if (!name || !lic) die(`${rel}: no name / license`);
    return {name: name[1], license: lic[1]};
  };
  const cli = npm('cli/package.json');
  const mcp = npm('mcp-server/package.json');
  const out = [
    {name: cli.name, license: cli.license, what: 'cli'},
    {name: mcp.name, license: mcp.license, what: 'mcp'},
    {...toml('forge/pyproject.toml'), what: 'forge'},
    {...toml('arena/pyproject.toml'), what: 'harness'},
  ];
  for (const l of out) if (!l.license) die(`${l.name} has no licence`);
  return out;
}

function requirements() {
  const node = JSON.parse(read('cli/package.json')).engines?.node;
  if (!node) die('cli/package.json has no engines.node');
  return {node};
}

const data = {
  _comment: 'GENERATED by cli/website/scripts/build-rails-data.mjs from the tools themselves — never edit by hand; its --check fails on drift.',
  anatomy: anatomy(),
  stages: stages(),
  choices: choices(),
  tiers: await tiers(),
  licences: licences(),
  requirements: requirements(),
};
const text = `${JSON.stringify(data, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : '';
  if (have !== text) die(`${path.relative(REPO, OUT)} is stale — the tools changed. Regenerate: node cli/website/scripts/build-rails-data.mjs`);
  console.log('[build-rails-data] site-data.json matches the tools');
} else {
  fs.writeFileSync(OUT, text);
  console.log(`[build-rails-data] wrote ${path.relative(REPO, OUT)}`);
}
