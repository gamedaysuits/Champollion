#!/usr/bin/env node
/**
 * build-seam-hubs.mjs — generate the homepage seam's "omnimodel hub" timeline
 * (website/src/data/seam-hubs.json) from the coverage SSOT, so the escalation
 * story (ever-bigger models, ever-larger claimed coverage) is DATA-DRIVEN and
 * cited, never hand-picked.
 *
 * Source (SSOT): shared/catalogue/method-coverage.json — per-method claimed
 * coverage imported cite-only from each provider's own published list.
 *
 * HONESTY (enforced here, fail-loud):
 *   • CITED-ONLY: a method ships as a hub ONLY if it carries source_url + asOf
 *     (its provider's own list, dated). Uncited entries are dropped LOUDLY.
 *   • Counts are the providers' own claims (`nature`/note in the SSOT); the
 *     seam labels them "claimed coverage" — coverage is not quality.
 *   • releaseDate / deployable fields pass through only when present in the
 *     SSOT (each itself cited there); this script never invents dates.
 *   • Parity: cli/scripts/check-prose-counts-parity.mjs asserts the emitted
 *     counts still equal the SSOT's (regen drift blocks the push).
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const SHARED = join(HERE, '..', 'shared');
const OUT = join(HERE, '..', 'website', 'src', 'data', 'seam-hubs.json');

const fail = (msg) => {
  throw new Error(`[build-seam-hubs] ${msg}`);
};

const src = JSON.parse(readFileSync(join(SHARED, 'catalogue', 'method-coverage.json'), 'utf8'));
if (!Array.isArray(src.methods) || !src.methods.length) fail('method-coverage.json has no methods[]');

const dropped = [];
const hubs = [];
for (const m of src.methods) {
  if (!m.key || !m.label) fail(`method entry missing key/label: ${JSON.stringify(m).slice(0, 80)}`);
  if (typeof m.count !== 'number' || m.count <= 0) {
    dropped.push(`${m.key} (count ${m.count})`);
    continue;
  }
  if (!m.source_url || !m.asOf) {
    dropped.push(`${m.key} (uncited: source_url=${!!m.source_url}, asOf=${!!m.asOf})`);
    continue;
  }
  if (m.tier !== 'service' && m.tier !== 'open') fail(`${m.key}: unknown tier '${m.tier}'`);
  const hub = {
    key: m.key,
    label: m.label,
    count: m.count,
    tier: m.tier,
    anyToAny: m.anyToAny === true,
    source_url: m.source_url,
    asOf: m.asOf,
  };
  // Optional, cited-in-SSOT extras (the omnimodel timeline + the deployable
  // honesty split). Passed through verbatim — never synthesized here.
  if (m.releaseDate) hub.releaseDate = m.releaseDate;
  if (m.deployable && typeof m.deployable.count === 'number') {
    if (!m.deployable.source_url) fail(`${m.key}: deployable.count without deployable.source_url`);
    hub.deployable = {
      count: m.deployable.count,
      note: m.deployable.note || null,
      source_url: m.deployable.source_url,
    };
  }
  hubs.push(hub);
}

if (hubs.length < 6) fail(`only ${hubs.length} cited hubs survived — coverage SSOT looks broken`);

// Timeline order: dated methods chronologically, then undated by count asc —
// the "bigger and bigger" escalation reads left-to-right/top-to-bottom.
hubs.sort((a, b) => {
  if (a.releaseDate && b.releaseDate) return a.releaseDate.localeCompare(b.releaseDate);
  if (a.releaseDate) return -1;
  if (b.releaseDate) return 1;
  return a.count - b.count;
});

const out = {
  _comment:
    'GENERATED by cli/scripts/build-seam-hubs.mjs — do not hand-edit. The homepage seam’s omnimodel ' +
    'hub timeline, from shared/catalogue/method-coverage.json (cite-only provider claims). Counts are ' +
    'CLAIMED coverage per each provider’s own published list — coverage is not quality.',
  _generatedFrom: ['shared/catalogue/method-coverage.json'],
  asOf: src.asOf,
  hubs,
};

writeFileSync(OUT, `${JSON.stringify(out, null, 2)}\n`);
console.log(
  `[build-seam-hubs] wrote ${OUT}\n  hubs (${hubs.length}): ${hubs.map((h) => `${h.label} ${h.count}${h.releaseDate ? ` (${h.releaseDate.slice(0, 4)})` : ''}`).join(' · ')}${dropped.length ? `\n  dropped (uncited/zero): ${dropped.join(', ')}` : ''}`,
);
