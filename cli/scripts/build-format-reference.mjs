#!/usr/bin/env node

/**
 * build-format-reference.mjs — generate the Formats reference page from the
 * framework schemas themselves.
 *
 * WHY THIS EXISTS
 *   Every tool on the rails (the champollion CLI, mt-eval, nmt-forge, the MCP
 *   server) reads the same six documents, defined ONCE in
 *   shared/schemas/framework/*.v1.schema.json. A hand-written page about
 *   those formats is a second copy that drifts; this page is DERIVED:
 *
 *     shared/schemas/framework/{project,set,method,gate-chain,deployment,
 *                               service-api}.v1.schema.json   (the SSOT)
 *       → this script
 *       → cli/website/docs/reference/formats.md   (derived, committed;
 *                                                  served at /docs/reference/formats)
 *
 * WHAT IT WRITES
 *   A short intro, then per schema: its id ($id, which is also the value of
 *   its `$schema` field), its title, what it is for (the schema's own
 *   description), and a table of every field — path (nested objects
 *   flattened as a.b, array items as a[].b), type or allowed values,
 *   whether it is required, and the schema's own description of it. A
 *   schema that defines several documents under $defs and no top-level
 *   fields (service-api/1: request, response, health, …) gets one table per
 *   document. Nothing is typed by hand except the intro.
 *
 * USAGE
 *   node cli/scripts/build-format-reference.mjs          # write the page
 *   node cli/scripts/build-format-reference.mjs --check  # exit 3 if the
 *                                                        # committed page is
 *                                                        # stale; writes
 *                                                        # nothing. Exit 1 =
 *                                                        # build error, NOT
 *                                                        # staleness (the
 *                                                        # site builders'
 *                                                        # contract).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CLI_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = path.resolve(CLI_DIR, '..');
// The monorepo-root SSOT first; the package's bundled copy (kept identical by
// sync-shared.mjs + shared-bundle-parity.test.js) in a standalone checkout.
const SCHEMA_DIRS = [
  path.join(REPO_ROOT, 'shared', 'schemas', 'framework'),
  path.join(CLI_DIR, 'shared', 'schemas', 'framework'),
];
export const SCHEMA_FILES = [
  'project.v1.schema.json',
  'set.v1.schema.json',
  'method.v1.schema.json',
  'gate-chain.v1.schema.json',
  'deployment.v1.schema.json',
  'service-api.v1.schema.json',
];
export const OUT_FILE = path.join(CLI_DIR, 'website', 'docs', 'reference', 'formats.md');
const REGEN = 'node cli/scripts/build-format-reference.mjs';

const INTRO = `---
title: Formats
slug: /reference/formats
description: Every document the rails read and write — project/1, set/1, method/1, gate-chain/1, deployment/1 and service-api/1 — field by field, generated from the schemas every tool validates against.
---

<!-- GENERATED by cli/scripts/build-format-reference.mjs from
     shared/schemas/framework/*.v1.schema.json — do not edit by hand.
     Regenerate after any schema change:  ${REGEN}
     Staleness check (exit 3), run by cli/test/format-reference.test.js:
       ${REGEN} --check -->

# Formats

Each thing on the rails has one format: a project, a data file's terms, a
method, a chain of checks, a deployment, and the \`/translate\` contract between
a translation service and what calls it. Each format is **versioned** (a
document names its format and version in \`$schema\`; a changed shape gets a new
version number, and the older one is still read) and **validated** against the
JSON Schema below.

Every tool reads these documents natively: the \`champollion\` CLI, \`mt-eval\`,
\`nmt-forge\` and the MCP server give the same verdict on the same file.

- \`champollion validate [folder]\` checks a project's files against these
  schemas: its \`champollion.project.json\`, every data sidecar
  (\`<file>.champollion.json\`), every \`method.json\`, its gate chains
  (\`gates/*.json\`) and its deployments (\`deploy/*.json\`). It reads no data
  file.
- \`champollion upgrade [folder]\` rewrites older shapes in the current format,
  losing nothing: a sidecar written before set/1 becomes set/1, and a key set/1
  does not know moves under \`x-<key>\`. An invalid sidecar is left for a person
  to fix. An older \`method.json\` is read as method/0 and left as it is.
  \`--dry\` says what would change and writes nothing.

Every document refuses keys it does not know, except keys that start with
\`x-\`: put your own notes there.

This page is generated from the schemas themselves, so every field on it is
exactly what the tools check.

`;

// ── schema walking ─────────────────────────────────────────────────────────

function loadSchema(file) {
  for (const dir of SCHEMA_DIRS) {
    const p = path.join(dir, file);
    if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf8'));
  }
  throw new Error(`schema not found: ${file} (looked in ${SCHEMA_DIRS.join(', ')})`);
}

/** Follow a local "#/$defs/x" reference (one level of indirection at a time). */
function deref(node, root) {
  let n = node;
  const seen = new Set();
  while (n && typeof n.$ref === 'string') {
    if (seen.has(n.$ref)) throw new Error(`circular $ref ${n.$ref}`);
    seen.add(n.$ref);
    const m = /^#\/\$defs\/(.+)$/.exec(n.$ref);
    if (!m || !root.$defs?.[m[1]]) throw new Error(`unresolvable $ref ${n.$ref}`);
    // the referring node's own description wins over the target's
    n = { ...root.$defs[m[1]], ...(n.description ? { description: n.description } : {}) };
  }
  return n;
}

const code = (v) => `\`${typeof v === 'string' ? v : JSON.stringify(v)}\``;

/** "string", "integer, 1–65535", one of `a`, `b`, "string matching `…`". */
function describeType(node, root) {
  if (node.const !== undefined) return code(node.const);
  if (Array.isArray(node.enum)) {
    return node.enum.length === 1 ? code(node.enum[0]) : `one of ${node.enum.map(code).join(', ')}`;
  }
  const types = Array.isArray(node.type) ? node.type : node.type ? [node.type] : [];
  let base = types.length ? types.join(' or ') : (node.properties ? 'object' : 'any');
  if (types.includes('array') || (!types.length && node.items)) {
    const items = node.items ? deref(node.items, root) : {};
    const inner = items.properties ? 'objects' : describeType(items, root);
    base = `array of ${inner}`;
    const bounds = [];
    if (node.minItems !== undefined && node.minItems === node.maxItems) bounds.push(`exactly ${node.minItems}`);
    else {
      if (node.minItems !== undefined) bounds.push(`at least ${node.minItems}`);
      if (node.maxItems !== undefined) bounds.push(`at most ${node.maxItems}`);
    }
    if (bounds.length) base += ` (${bounds.join(', ')})`;
    return base;
  }
  const extra = [];
  if (node.pattern) extra.push(`matching ${code(node.pattern)}`);
  if (node.minLength) extra.push('not empty');
  if (node.minimum !== undefined && node.maximum !== undefined) extra.push(`${node.minimum}–${node.maximum}`);
  else if (node.minimum !== undefined) extra.push(`≥ ${node.minimum}`);
  else if (node.maximum !== undefined) extra.push(`≤ ${node.maximum}`);
  return extra.length ? `${base}, ${extra.join(', ')}` : base;
}

/**
 * Flatten an object schema into rows {path, type, required, description}.
 * Nested objects with properties become a.b rows; arrays of objects a[].b.
 */
function flatten(node, root, prefix, rows) {
  const obj = deref(node, root);
  const required = new Set(obj.required || []);
  for (const [key, raw] of Object.entries(obj.properties || {})) {
    const child = deref(raw, root);
    const p = prefix ? `${prefix}.${key}` : key;
    rows.push({ path: p, type: describeType(child, root), required: required.has(key),
      description: child.description || '' });
    if (child.properties || child.patternProperties) flatten(child, root, p, rows);
    const items = child.items ? deref(child.items, root) : null;
    if (items?.properties) flatten(items, root, `${p}[]`, rows);
  }
  for (const [pattern, raw] of Object.entries(obj.patternProperties || {})) {
    const child = deref(raw, root);
    if (pattern === '^x-') {
      rows.push({ path: prefix ? `${prefix}.x-*` : 'x-*', type: 'any', required: false,
        description: 'Your own notes: any key starting with `x-` is kept and never checked.' });
    } else {
      const p = pattern === '^' ? `${prefix ? `${prefix}.` : ''}<key>`
        : `${prefix ? `${prefix}.` : ''}<key matching ${pattern}>`;
      rows.push({ path: p, type: describeType(child, root), required: false,
        description: child.description || (pattern === '^' ? 'One entry per key.' : '') });
      if (child.properties) flatten(child, root, p, rows);
    }
  }
}

// ── markdown ───────────────────────────────────────────────────────────────

/** Escape what CommonMark would misread OUTSIDE `code` spans: `<word …>` as a
 *  raw HTML tag, a stray `*` as emphasis. Inside a code span text is literal. */
function escapeMd(text) {
  return String(text).split(/(`[^`]*`)/).map((part, i) =>
    i % 2 ? part : part.replace(/</g, '&lt;').replace(/\*/g, '\\*')).join('');
}

const cell = (text) => escapeMd(String(text ?? '').replace(/\s+/g, ' ').trim()).replace(/\|/g, '\\|');
const prose = (text) => escapeMd(String(text ?? '').replace(/\s+/g, ' ').trim());

function table(rows) {
  const out = ['| Field | Type | Required | Description |', '|---|---|---|---|'];
  for (const r of rows) {
    // a path is shown as code; <key> placeholders inside code stay literal
    out.push(`| \`${r.path}\` | ${cell(r.type)} | ${r.required ? 'yes' : ''} | ${cell(r.description)} |`);
  }
  return out.join('\n');
}

/** "https://champollion.dev/schemas/project/1.json" → "project/1" */
function shortName(id) {
  const m = /\/schemas\/(.+)\/(\d+)\.json$/.exec(id || '');
  if (!m) throw new Error(`schema $id is not a champollion schema id: ${id}`);
  return `${m[1]}/${m[2]}`;
}

function renderSchema(file) {
  const schema = loadSchema(file);
  const id = schema.$id || schema.properties?.$schema?.enum?.[0] || schema.properties?.$schema?.const;
  if (!id) throw new Error(`${file} has no $id and no $schema value`);
  const name = shortName(id);
  const lines = [];
  lines.push(`## ${name}`, '');
  if (schema.title) lines.push(`**${prose(schema.title)}**`, '');
  lines.push(`Schema id: \`${id}\``
    + (schema.properties?.$schema ? ' — a document in this format says so in its `$schema` field. ' : '. ')
    + `Schema file: \`shared/schemas/framework/${file}\`.`, '');
  if (schema.description) lines.push(prose(schema.description), '');

  if (schema.properties) {
    const rows = [];
    flatten(schema, schema, '', rows);
    lines.push(table(rows), '');
    if (schema.additionalProperties === false) {
      lines.push('Keys not listed here are refused'
        + (schema.patternProperties?.['^x-'] ? ', except your own `x-` keys.' : '.'), '');
    }
    lines.push('A **yes** in Required on a nested field (`a.b`) means: required whenever `a` is present.', '');
  } else if (schema.$defs) {
    lines.push(`${name} has no fields of its own: it defines the bodies the contract's `
      + 'requests and answers carry, each below.', '');
    for (const [defName, def] of Object.entries(schema.$defs)) {
      const d = deref(def, schema);
      if (!d.properties) continue;
      lines.push(`### ${name}: \`${defName}\``, '');
      if (d.description) lines.push(prose(d.description), '');
      const rows = [];
      flatten(d, schema, '', rows);
      lines.push(table(rows), '');
    }
  } else {
    throw new Error(`${file} defines no fields and no documents`);
  }
  return lines.join('\n');
}

export function build() {
  const parts = [INTRO.trimEnd(), ''];
  parts.push('| Format | What it is |', '|---|---|');
  for (const file of SCHEMA_FILES) {
    const s = loadSchema(file);
    const name = shortName(s.$id);
    parts.push(`| [${name}](#${name.replace('/', '')}) | ${cell(s.title || '')} |`);
  }
  parts.push('');
  for (const file of SCHEMA_FILES) parts.push(renderSchema(file));
  return parts.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

function main() {
  const CHECK = process.argv.includes('--check');
  try {
    const page = build();
    if (CHECK) {
      const committed = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : null;
      if (committed !== page) {
        console.error(`${path.relative(REPO_ROOT, OUT_FILE)} is stale (a framework schema changed). `
          + `Regenerate: ${REGEN}`);
        process.exit(3);
      }
      console.error('formats reference is current.');
      process.exit(0);
    }
    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    fs.writeFileSync(OUT_FILE, page);
    console.error(`wrote ${path.relative(REPO_ROOT, OUT_FILE)} (${page.length} bytes)`);
  } catch (err) {
    console.error(`build-format-reference: ${err.message}`);
    process.exit(1);
  }
}

/** Run as a script (not imported by a test): compare real paths, since a
 *  temp dir or a symlinked checkout makes argv[1] and import.meta.url differ. */
function invokedDirectly() {
  if (!process.argv[1]) return false;
  try {
    return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (invokedDirectly()) main();
