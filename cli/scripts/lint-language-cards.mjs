// ─── Main ──────────────────────────────────────────────────────

async function main() {
  if (!JSON_OUTPUT && !CI_MODE) {
    console.log('═══════════════════════════════════════════════════════════');
    console.log('  Champollion Language Card Linter');
    console.log('  Validates card data quality, consistency, and completeness');
    console.log('═══════════════════════════════════════════════════════════\n');
  }

  // ── Load validation data sets ──
  if (!JSON_OUTPUT) console.log('Loading validation data...');

  const nllbCodes = loadCodeSet(NLLB_CODES_JSON, 'NLLB-200 codes');
  const nllbFullCodes = buildNllbFullCodeSet(nllbCodes);
  const floresCodes = loadCodeSet(FLORES_CODES_JSON, 'FLORES+ codes');
  const licenseRegister = loadLicenseRegister(SHARED_LICENSES_JSON);
  const explainers = loadExplainers();
  const cardSchema = loadCardSchema();
  const speakerFacts = loadSpeakerFacts();

  const dataMeta = {
    nllb: nllbCodes ? { loaded: true, count: nllbCodes.size } : { loaded: false, reason: 'File not found' },
    flores: floresCodes ? { loaded: true, count: floresCodes.size } : { loaded: false, reason: 'File not found' },
    licenses: licenseRegister
      ? { loaded: true, count: licenseRegister.sourceKeys.size }
      : { loaded: false, reason: 'File not found' },
    explainers: explainers
      ? { loaded: true, features: explainers.featureIds.size, glossaryVocab: explainers.glossaryVocab.size }
      : { loaded: false, reason: 'File not found' },
    cardSchema: cardSchema ? { loaded: true } : { loaded: false, reason: 'File not found' },
  };

  if (!JSON_OUTPUT) {
    if (nllbCodes) {
      console.log(`  NLLB-200: ${nllbCodes.size} codes loaded`);
    } else {
      console.warn('  ⚠️  NLLB-200 codes not found — nllb-code-valid rule will be skipped');
    }
    if (floresCodes) {
      console.log(`  FLORES+: ${floresCodes.size} codes loaded`);
    } else {
      console.warn('  ⚠️  FLORES+ codes not found — flores-code-valid rule will be skipped');
    }
    if (licenseRegister) {
      console.log(`  License register: ${licenseRegister.sourceKeys.size} sources loaded`);
    } else {
      console.warn('  ⚠️  shared/licenses.json not found — license rules will be skipped');
    }
    if (explainers) {
      console.log(`  Explainers: ${explainers.featureIds.size} features, ` +
                  `${explainers.glossaryVocab.size} glossary term variants loaded`);
    } else {
      console.warn('  ⚠️  shared/explainers/ not found — explainer rules will be skipped');
    }
    if (cardSchema) {
      console.log('  Card schema: loaded (structural validation = warn-not-fail)');
    } else {
      console.warn('  ⚠️  language-card.schema.json not found — schema validation will be skipped');
    }
  }

  // ── Build rules with loaded context ──
  const context = {
    nllbCodes,
    nllbFullCodes,
    floresCodes,
    licenseRegister,
    explainers,
    // R2 reconciliation source (Map or null — null ⇒ on-card speakerEstimates[]).
    facts: speakerFacts,
    // Aggregated across all cards by the license-source-resolves rule,
    // reported once at the end (per-card messages would drown the output).
    unresolvedSourceCounts: new Map(),
    // Aggregated by explainer-coverage / glossary-coverage rules.
    missingFeatureCounts: new Map(),
    unknownTermCounts: new Map(),
  };
  const rules = buildRules(context);

  // ── Discover card files ──
  let cardFiles;
  try {
    cardFiles = fs.readdirSync(CARDS_DIR)
      .filter(f => f.endsWith('.json') && f !== 'language-tree.json');
  } catch (err) {
    console.error(`FATAL: Cannot read cards directory: ${CARDS_DIR}`);
    console.error(`  ${err.message}`);
    process.exit(1);
  }

  // Filter to single language if requested
  if (SINGLE_LANG) {
    const target = `${SINGLE_LANG}.json`;
    if (!cardFiles.includes(target)) {
      console.error(`FATAL: Card file not found: ${target}`);
      process.exit(1);
    }
    cardFiles = [target];
  }

  if (!JSON_OUTPUT) {
    console.log(`\nLinting ${cardFiles.length.toLocaleString()} cards...`);
  }

  // ── Handle --fix mode ──
  if (FIX_MODE && !JSON_OUTPUT) {
    console.log('  (--fix mode: no auto-fixable rules defined yet)');
  }

  // ── Run lint passes ──
  const allDiagnostics = [];
  // Flat-card index for the cross-card taxonomy post-pass
  const cardIndex = new Map();

  for (const filename of cardFiles) {
    const filePath = path.join(CARDS_DIR, filename);

    // Step 1: Parse JSON — the valid-json rule is implicit here
    let card;
    try {
      const raw = fs.readFileSync(filePath, 'utf-8');
      card = normalizeCard(JSON.parse(raw));
    } catch (err) {
      // JSON parse failure — emit the valid-json error and skip other rules.
      // There's nothing meaningful to lint if we can't read the file.
      allDiagnostics.push({
        ruleId: 'valid-json',
        severity: 'error',
        filename,
        message: `Invalid JSON: ${err.message}`,
      });
      continue;
    }

    if (card.code) cardIndex.set(card.code, card);

    // Step 2: Run all other rules on the parsed card
    const cardDiags = lintCard(filename, card, rules, context);
    allDiagnostics.push(...cardDiags);

    // Step 3: Structural schema validation (AJV-style; warning-only)
    allDiagnostics.push(...schemaValidateCard(filename, card, cardSchema));
  }

  // ── genera/ sweep: stale-TODO check only ──
  // genera/ is exempt by charter from the atlas-shape rules (hand-authored
  // parents, no _atlas stamp — see genera/README.md), so the main rule loop
  // deliberately skips it. But hand-authored is exactly where placeholder
  // TODO strings linger (8 shipped as data values for months), so the
  // no-stale-todo rule alone sweeps this directory too.
  if (!SINGLE_LANG) {
    const generaDir = path.join(CARDS_DIR, 'genera');
    if (fs.existsSync(generaDir)) {
      for (const f of fs.readdirSync(generaDir).filter(n => n.endsWith('.json'))) {
        let generaCard;
        try {
          generaCard = JSON.parse(fs.readFileSync(path.join(generaDir, f), 'utf-8'));
        } catch (err) {
          allDiagnostics.push({
            ruleId: 'valid-json',
            severity: 'error',
            filename: `genera/${f}`,
            message: `Invalid JSON: ${err.message}`,
          });
          continue;
        }
        const staleTodos = findTodoStrings(generaCard)
          .filter(t => !TODO_EXPECTED_FIELDS.has(t.path));
        if (staleTodos.length > 0) {
          const first = staleTodos[0];
          const suffix = staleTodos.length > 1
            ? ` (+${staleTodos.length - 1} more)` : '';
          allDiagnostics.push({
            ruleId: 'no-stale-todo',
            severity: 'warning',
            filename: `genera/${f}`,
            message: `TODO string at '${first.path}': '${first.value}'${suffix}`,
          });
        }
      }
    }
  }

  // ── Cross-card taxonomy rules (docs/LANGUAGE_TAXONOMY.md R5) ──
  // Needs the full card set, so it runs as a post-pass and is skipped
  // in --lang mode (a single card cannot be bijection-checked).
  const membersByMacro = loadMacroTable();
  if (membersByMacro && !SINGLE_LANG) {
    allDiagnostics.push(...lintTaxonomy(cardIndex, membersByMacro));
  } else if (!membersByMacro && !JSON_OUTPUT) {
    console.warn('  ⚠️  iso-639-3-macrolanguages.tab not found — taxonomy rules will be skipped');
  }

  // ── Lint corpora cards (license fields) ──
  // Corpus metadata cards carry a license.spdx field that must be a known
  // SPDX(-ish) identifier present in the shared license register. Skipped
  // when --lang is given (that flag targets a single language card).
  if (licenseRegister && !SINGLE_LANG && fs.existsSync(CORPORA_DIR)) {
    const corporaFiles = fs.readdirSync(CORPORA_DIR).filter(f => f.endsWith('.json'));
    if (!JSON_OUTPUT) {
      console.log(`Linting ${corporaFiles.length} corpora cards...`);
    }

    for (const filename of corporaFiles) {
      let card;
      try {
        card = JSON.parse(fs.readFileSync(path.join(CORPORA_DIR, filename), 'utf-8'));
      } catch (err) {
        allDiagnostics.push({
          ruleId: 'valid-json',
          severity: 'error',
          filename: `corpora-cards/${filename}`,
          message: `Invalid JSON: ${err.message}`,
        });
        continue;
      }

      const lic = card.license;
      const spdx = (lic && typeof lic === 'object') ? lic.spdx : lic;

      if (!spdx || typeof spdx !== 'string') {
        allDiagnostics.push({
          ruleId: 'corpora-license-known',
          severity: 'error',
          filename: `corpora-cards/${filename}`,
          message: 'Missing license.spdx field',
        });
        continue;
      }

      // SPDX defines 'LicenseRef-…' as the standard mechanism for licenses
      // outside the canonical list — such values can NEVER appear in an
      // SPDX vocabulary, so requiring register membership for them was a
      // category error (the register itself carries 16+ LicenseRef-*
      // entries only by historical accident of which sources were
      // registered first). Accept a LicenseRef value IFF the corpora card
      // SELF-DOCUMENTS the custom terms: well-formed idstring, explicit
      // commercial/redistribution booleans, and non-empty notes — that is
      // what license-gating (license_use.py lanes) actually consumes.
      // Bare/undocumented LicenseRef strings still fail. (Rule updated
      // 2026-07-07; previously failed AraBench/TWB-Gamayun/WMT cards.)
      const isSelfDocumentedLicenseRef =
        /^LicenseRef-[A-Za-z0-9.-]+$/.test(spdx) &&
        lic && typeof lic === 'object' &&
        typeof lic.commercial === 'boolean' &&
        typeof lic.redistribution === 'boolean' &&
        typeof lic.notes === 'string' && lic.notes.trim().length > 0;

      if (!licenseRegister.spdxSet.has(spdx) && !isSelfDocumentedLicenseRef) {
        // Tolerate formatting drift ("CC BY-NC-SA 4.0" vs "CC-BY-NC-SA-4.0")
        // only enough to produce a precise message — it is still a violation.
        const normalized = spdx.trim().replace(/\s+/g, '-');
        const hint = licenseRegister.spdxSet.has(normalized)
          ? ` (non-canonical format — register has '${normalized}')`
          : '';
        allDiagnostics.push({
          ruleId: 'corpora-license-known',
          severity: 'error',
          filename: `corpora-cards/${filename}`,
          message: `license.spdx '${spdx}' is not a known SPDX value in shared/licenses.json` +
            ` and is not a self-documented LicenseRef${hint}`,
        });
      }
    }
  }

  // ── Explainer dataset internal integrity ──
  // The glossary's related-links must resolve within the glossary itself;
  // a dangling link is a data bug in shared/explainers/glossary.json.
  if (explainers && explainers.glossaryIntegrityErrors.length > 0) {
    for (const msg of explainers.glossaryIntegrityErrors) {
      allDiagnostics.push({
        ruleId: 'glossary-internal-links',
        severity: 'error',
        filename: 'shared/explainers/glossary.json',
        message: msg,
      });
    }
  }

  // ── Explainer coverage summaries ──
  if (!JSON_OUTPUT && context.missingFeatureCounts.size > 0) {
    const sorted = [...context.missingFeatureCounts.entries()].sort((a, b) => b[1] - a[1]);
    console.log(`\n  EXPLAINER GAPS (${sorted.length} distinct feature ids):`);
    console.log('  These surfaced feature ids have no tc-features.json entry.');
    console.log('  Fix by extending scripts/build-explainers.mjs, NOT by editing cards.');
    for (const [id, count] of sorted.slice(0, 25)) {
      console.log(`    ${String(count).padStart(6)} cards  ${id}`);
    }
  }
  if (!JSON_OUTPUT && context.unknownTermCounts.size > 0) {
    const sorted = [...context.unknownTermCounts.entries()].sort((a, b) => b[1] - a[1]);
    console.log(`\n  UNKNOWN-TERM WATCHLIST HITS (${sorted.length} distinct terms):`);
    console.log('  Watchlisted technical terms found in rendered card text without a');
    console.log('  glossary.json entry yet. Fix by writing the glossary entry.');
    for (const [term, count] of sorted) {
      console.log(`    ${String(count).padStart(6)} cards  ${term}`);
    }
  }

  // ── License register gap summary ──
  // Per-card diagnostics tell you WHICH cards are affected; this summary
  // tells you WHICH source ids need register entries (the actual fix).
  if (!JSON_OUTPUT && context.unresolvedSourceCounts.size > 0) {
    const sorted = [...context.unresolvedSourceCounts.entries()]
      .sort((a, b) => b[1] - a[1]);
    console.log(`\n  LICENSE REGISTER GAPS (${sorted.length} distinct source ids):`);
    console.log('  These source ids appear in cards but have no entry in shared/licenses.json.');
    console.log('  Fix by registering the source license (tc-licenses.json), NOT by editing cards.');
    const shown = sorted.slice(0, 25);
    for (const [id, count] of shown) {
      console.log(`    ${String(count).padStart(6)} cards  ${id}`);
    }
    if (sorted.length > shown.length) {
      console.log(`    ... and ${sorted.length - shown.length} more (use --json for the full list)`);
    }
  }

  // ── Card-integrity focus summary (R1–R6) ──
  // The focused gate cares about these four rules; surface their tally
  // explicitly so "0 violations post-regen" is greppable regardless of
  // pre-existing, out-of-scope errors elsewhere in the corpus.
  const integritySet = new Set(CARD_INTEGRITY_RULE_IDS);
  const integrityErrors = allDiagnostics.filter(
    d => d.severity === 'error' && integritySet.has(d.ruleId)
  );
  if (!JSON_OUTPUT) {
    console.log('  CARD-INTEGRITY GATE (R1–R6):');
    const byRule = new Map(CARD_INTEGRITY_RULE_IDS.map(id => [id, 0]));
    for (const d of integrityErrors) byRule.set(d.ruleId, byRule.get(d.ruleId) + 1);
    for (const [id, n] of byRule) {
      console.log(`    ${n === 0 ? '✓' : '✗'} ${id}: ${n.toLocaleString()} violation(s)`);
    }
    console.log(`    → ${integrityErrors.length === 0 ? 'GREEN — 0 integrity violations' : `RED — ${integrityErrors.length.toLocaleString()} integrity violation(s)`}`);
    console.log('');
  }

  // ── Output results ──
  if (JSON_OUTPUT) {
    const report = buildJsonReport(
      allDiagnostics, cardFiles.length, dataMeta, context.unresolvedSourceCounts
    );
    report.cardIntegrity = {
      ruleIds: CARD_INTEGRITY_RULE_IDS,
      violations: integrityErrors.length,
      pass: integrityErrors.length === 0,
    };
    // Write to stdout as formatted JSON for piping into other tools
    console.log(JSON.stringify(report, null, 2));
  } else {
    printConsoleSummary(allDiagnostics, cardFiles.length);
    console.log('');
  }

  // ── Exit code ──
  // Warnings and info never fail. Two error contracts:
  //   --integrity-ci : exit 1 ONLY on R1–R6 violations (the focused gate; goes
  //                    green once the cards are fixed, ignoring pre-existing
  //                    out-of-scope errors). All rules still ran and reported.
  //   default / --ci : exit 1 on ANY error (full-hygiene contract).
  const errorCount = allDiagnostics.filter(d => d.severity === 'error').length;
  if (INTEGRITY_CI) {
    if (integrityErrors.length > 0) process.exit(1);
  } else if (errorCount > 0) {
    process.exit(1);
  }
}

main().catch(err => {
  console.error('FATAL:', err);
  process.exit(1);
});
