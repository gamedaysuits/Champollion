/**
 * Recursively find all string values in an object that look like TODOs.
 * Returns array of { path, value } for each TODO string found.
 *
 * WHY recursive: Cards have deeply nested structures (methodSupport,
 * classification, vitality, etc.) and stale TODOs can hide anywhere.
 */
function findTodoStrings(obj, currentPath = '') {
  const results = [];
  if (obj === null || obj === undefined) return results;

  if (typeof obj === 'string') {
    if (obj === 'TODO' || obj.startsWith('TODO:') || obj.startsWith('TODO ')) {
      results.push({ path: currentPath, value: obj });
    }
    return results;
  }

  if (Array.isArray(obj)) {
    for (let i = 0; i < obj.length; i++) {
      results.push(...findTodoStrings(obj[i], `${currentPath}[${i}]`));
    }
    return results;
  }

  if (typeof obj === 'object') {
    for (const [key, value] of Object.entries(obj)) {
      const childPath = currentPath ? `${currentPath}.${key}` : key;
      results.push(...findTodoStrings(value, childPath));
    }
  }

  return results;
}


function buildRules(context) {
  return [

    // ── Error-severity rules ─────────────────────────────────

    {
      id: 'valid-json',
      severity: 'error',
      describe: 'File is valid JSON',
      // This rule is handled specially during file loading — if JSON.parse
      // fails, we emit a valid-json error and skip all other rules for
      // that file. The check function here is a no-op since by the time
      // we run rules, the card has already been parsed.
      check: () => null,
    },

    {
      id: 'has-name',
      severity: 'error',
      describe: 'Card has non-empty name field',
      check: (card) => {
        if (!card.name || typeof card.name !== 'string' || card.name.trim() === '') {
          return 'Missing or empty name field';
        }
        return null;
      },
    },

    {
      id: 'has-iso639-3',
      severity: 'error',
      describe: 'Card has iso639_3 field',
      check: (card) => {
        // BCP 47 private-use conlang cards ('x-…', e.g. x-pirate) are
        // register-only constructs: ISO 639-3 does not and cannot assign
        // them codes, so the requirement is definitionally inapplicable.
        // (Rule scoped 2026-07-07; the fictional cards ship iso639_3: null.)
        if (isPrivateUseCard(card) || isGlottologOnlyCard(card)) return null;
        if (!card.iso639_3 || typeof card.iso639_3 !== 'string') {
          return 'Missing iso639_3 field';
        }
        return null;
      },
    },

    {
      id: 'lyss-module-language-match',
      severity: 'error',
      describe: 'LYSS evalMetrics modules target this card’s own language subpackage',
      check: (card) => {
        // Guardrail for the one-package, many-languages LYSS design: a card's
        // referee metrics are loaded by the module path declared in its
        // evalMetrics (e.g. crk.json → champollion_lyss.crk.metrics). The
        // second dotted segment IS the language selector inside the single
        // champollion-lyss package, so it MUST equal this card's own language
        // code — otherwise a typo could make (say) oji.json silently load
        // Cree's referee metrics. Only the champollion_lyss package is
        // constrained; harness-provided, language-NEUTRAL metrics
        // (mt_eval_harness.plugins.*, e.g. igt_gloss / morph_segmentation) are
        // intentionally exempt. 'core'/'common'/'base' are reserved for a
        // future shared LYSS layer (imported by language modules, not declared
        // on cards) so they never false-positive.
        const em = card.evalMetrics;
        if (!em || typeof em !== 'object') return null;
        const langCode = card.iso639_3 || card.code;
        if (!langCode) return null;
        const RESERVED = new Set(['core', 'common', 'base']);
        for (const [key, decl] of Object.entries(em)) {
          const mod = decl && decl.module;
          if (typeof mod !== 'string') continue;
          const segs = mod.split('.');
          if (segs[0] !== 'champollion_lyss') continue;
          const langSeg = segs[1];
          if (langSeg && langSeg !== langCode && !RESERVED.has(langSeg)) {
            return `evalMetrics['${key}'].module '${mod}' targets language ` +
              `subpackage '${langSeg}' but this is the '${langCode}' card — a ` +
              `LYSS module must live under champollion_lyss.<this card’s language>`;
          }
        }
        return null;
      },
    },

    {
      id: 'has-classification',
      severity: 'error',
      describe: 'Card resolvable in Glottolog has classification.family',
      check: (card) => {
        // Some languages are legitimate isolates or unclassified, but they
        // should still have the classification object — isolates use
        // classification.family set to 'Language isolate'.
        //
        // Scope (2026-07-07): this rule ERRORS only where the family is
        // actually derivable — the card has a glottocode (Glottolog knows
        // the languoid, so build-language-tree.mjs must have filled the
        // family) or already carries a partial classification with a
        // family-bearing upstream. Cards Glottolog 5.3 cannot resolve at
        // all (historic/ancient/retired ISO codes with no languoid) are
        // covered by the warning-level 'classification-unresolved' rule
        // below — an upstream coverage gap, not a generator defect.
        // Private-use conlangs ('x-…') are exempt outright.
        //
        // Honest no-family representation (2026-07-07): entries Glottolog
        // files under a housekeeping bucket (e.g. 'Bookkeeping', book1242 —
        // spurious/unattested/retired codes) deliberately carry
        // family: null plus the bucket glottocode and a cited note (see
        // build-language-tree.mjs). That is a complete classification —
        // "no family asserted" is what the source actually says — not a
        // missing one.
        if (isPrivateUseCard(card)) return null;
        // A recorded bucket IS a complete classification: it says, citing
        // Glottolog's own glottocode, that Glottolog asserts no family here.
        // The old generator paired it with a hand-written note and this rule
        // demanded one; the atlas cites the bucket code itself, so the note is
        // no longer where the citation lives. `family` is ABSENT rather than
        // explicitly null for the same reason every other unasserted field is
        // absent — the projector omits what no source claims.
        if (card.classification &&
            typeof card.classification.glottologBucket === 'string' &&
            card.classification.glottologBucket.length > 0 &&
            !card.classification.family) {
          return null;
        }
        // AN ISOLATE HAS NO FAMILY. That is the whole meaning of the word.
        //
        // The old corpus wrote the string 'Language isolate' into the family
        // slot; the atlas states it once, as the boolean `isIsolate` that
        // Glottolog's own family_id implies, and leaves family unasserted. All
        // 150 cards this rule was failing are isolates — it was demanding a
        // family for languages whose defining property is not having one.
        if (card.isIsolate === true || card.isIsolate === '1') return null;

        if (!card.classification || !card.classification.family) {
          if (!card.glottocode) return null; // → classification-unresolved
          return 'Missing classification.family';
        }
        return null;
      },
    },

    {
      id: 'no-bookkeeping-family',
      severity: 'error',
      describe: "Glottolog housekeeping buckets (Bookkeeping, Unclassifiable, Unattested, Artificial Language, Speech Register, Pidgin, Mixed Language) are never presented as language families",
      check: (card) => {
        // Glottolog's housekeeping pseudo-families are buckets, not
        // genealogical families — displaying one as a family misrepresents
        // the source. The honest representation is family: null +
        // glottologBucket + cited note (regenerate via
        // build-language-tree.mjs --enrich, the authoritative mapping).
        //
        // pidg1258 'Pidgin' and mixe1287 'Mixed Language' are flagged too,
        // per founder direction (2026-07-07): meaningful contact-language
        // TYPES, but still not genealogical families — the type
        // information lives in the cited note.
        const BUCKETS = {
          book1242: 'Bookkeeping',
          uncl1493: 'Unclassifiable',
          unat1236: 'Unattested',
          arti1236: 'Artificial Language',
          spee1234: 'Speech Register',
          pidg1258: 'Pidgin',
          mixe1287: 'Mixed Language',
        };
        const BUCKET_NAMES = new Set(Object.values(BUCKETS));
        const cl = card.classification;
        if (!cl) return null;

        // `family` may be an attribution envelope, so compare against every
        // value it carries rather than against the object (which stringifies
        // to "[object Object]" and matched nothing while failing everything).
        const familyClaims = (cl.family && typeof cl.family === 'object'
          && Array.isArray(cl.family.values))
          ? cl.family.values.map((v) => v?.value)
          : [cl.family];
        const namedBucket = familyClaims.find((v) => BUCKET_NAMES.has(v));

        // Sitting UNDER a bucket is fine and true; PRESENTING it as a family
        // is what this rule forbids. The atlas records the bucket in its own
        // `glottologBucket` field and asserts no family at all, which is
        // exactly the honest shape the rule was written to demand — so that
        // shape passes.
        const declaresBucket = typeof cl.glottologBucket === 'string'
          && cl.glottologBucket.length > 0;
        if (namedBucket || (BUCKETS[cl.familyGlottocode] && !declaresBucket)) {
          const label = namedBucket || BUCKETS[cl.familyGlottocode];
          return `classification presents Glottolog's '${label}' housekeeping bucket as a family — regenerate via build-language-tree.mjs --enrich`;
        }
        // A bucket from Glottolog beside a family from WALS is NOT a defect.
        // WALS classifies Kija Pidgin genealogically; Glottolog files it under
        // Pidgin. Two catalogues answering differently is exactly what the
        // attribution envelope exists to show, so only GLOTTOLOG asserting a
        // family while ALSO bucketing the language would be self-contradiction.
        const glottologFamily = (cl.family && typeof cl.family === 'object'
          && Array.isArray(cl.family.values))
          ? cl.family.values.some((v) => /^glottolog/i.test(v?.source ?? '') && v?.value)
          : false;
        if (declaresBucket && glottologFamily) {
          return `Glottolog both names a family and files this language under the `
            + `'${cl.glottologBucket}' bucket — it cannot be doing both`;
        }

        if (Array.isArray(cl.ancestry)) {
          const hit = cl.ancestry.find(a => BUCKET_NAMES.has(a));
          if (hit) {
            return `classification.ancestry contains the '${hit}' housekeeping bucket`;
          }
        }
        if (cl.family === null &&
            (typeof cl.glottologBucket !== 'string' || typeof cl.note !== 'string' || cl.note.length === 0)) {
          return 'classification.family is null without the glottologBucket + cited note that justify it';
        }
        return null;
      },
    },

    {
      id: 'classification-unresolved',
      severity: 'warning',
      describe: 'Card has no Glottolog languoid and no classification.family (upstream coverage gap)',
      // TODO(2026-07-07): these are ISO codes Glottolog 5.3 ships no
      // languoid for (mostly historic/ancient/retired codes). Revisit on
      // the next Glottolog upgrade, or classify via curated additions to
      // build-language-tree.mjs if the languages become launch-relevant.
      check: (card) => {
        if (isPrivateUseCard(card)) return null;
        if (card.glottocode) return null; // handled by has-classification
        if (!card.classification || !card.classification.family) {
          return 'No Glottolog languoid resolvable for this code — classification.family unavailable';
        }
        return null;
      },
    },

    {
      id: 'dataSources-not-empty',
      severity: 'error',
      describe: 'dataSources has at least one entry',
      check: (card) => {
        if (!card.dataSources || !Array.isArray(card.dataSources) || card.dataSources.length === 0) {
          return 'dataSources is missing or empty';
        }
        return null;
      },
    },

    {
      id: 'filename-matches-code',
      severity: 'error',
      describe: 'Filename matches card.code or card.iso639_3',
      check: (card, filename) => {
        const fileCode = filename.replace('.json', '');
        const codeMatch = card.code === fileCode || card.iso639_3 === fileCode;
        if (!codeMatch) {
          return `Filename '${filename}' does not match card.code='${card.code}' or card.iso639_3='${card.iso639_3}'`;
        }
        return null;
      },
    },

    {
      id: 'nllb-code-valid',
      severity: 'error',
      describe: 'If NLLB supported, the code matches actual NLLB-200 list',
      check: (card) => {
        // Skip this rule entirely if the NLLB data file wasn't available
        if (!context.nllbCodes) return null;

        const nllb = card.methodSupport?.nllb;
        if (!nllb || !nllb.supported) return null;

        // Card claims NLLB support — verify the code exists
        if (!nllb.code) {
          return 'NLLB marked as supported but no code specified';
        }

        if (!context.nllbFullCodes.has(nllb.code)) {
          return `NLLB code '${nllb.code}' not in NLLB-200 actual list`;
        }

        // Also verify the NLLB code starts with the right ISO 639-3 prefix.
        // This catches cases where e.g., pam.json claims nllb code "crk_Cans".
        const iso3 = card.iso639_3 || card.code;
        const nllbIsoPrefix = nllb.code.split('_')[0];
        if (iso3 && nllbIsoPrefix !== iso3) {
          // Check if it's a legitimate mapping (the NLLB data file maps
          // the card's ISO code to this full code)
          const expectedCode = context.nllbCodes.get(iso3);
          if (expectedCode !== nllb.code) {
            return `NLLB code '${nllb.code}' prefix '${nllbIsoPrefix}' does not match card ISO '${iso3}'`;
          }
        }

        return null;
      },
    },

    {
      id: 'flores-code-valid',
      severity: 'error',
      describe: 'evalDatasets only lists FLORES+ if language is actually in FLORES+',
      check: (card) => {
        // Skip this rule if the FLORES data file wasn't available
        if (!context.floresCodes) return null;

        const hasFlores = card.evalDatasets?.some(d =>
          d === 'flores-plus-devtest' || d === 'flores-devtest'
        );

        if (!hasFlores) return null;

        const iso3 = card.iso639_3 || card.code;
        if (!context.floresCodes.has(iso3)) {
          return `Claims FLORES+ in evalDatasets but ISO '${iso3}' is not in FLORES+ actual list`;
        }

        return null;
      },
    },

    {
      id: 'explainer-coverage',
      severity: 'error',
      describe: 'Every typological feature ID surfaced on a card resolves to shared/explainers/tc-features.json',
      // WHY error: if the UI cannot join a surfaced feature to its
      // explainer, users see raw keys/codes (the "category 6" bug).
      // Coverage gaps are fixed in build-explainers.mjs, not on cards.
      check: (card) => {
        if (!context.explainers) return null;
        const { featureIds, propertyIndex } = context.explainers;
        const missing = new Set();

        // (a) typologicalProfile keys — the card's surfaced feature set
        if (card.typologicalProfile && typeof card.typologicalProfile === 'object') {
          for (const key of Object.keys(card.typologicalProfile)) {
            if (TYPOLOGY_META_KEYS.has(key)) continue;
            if (propertyIndex[`card|${key}`] || propertyIndex[`grambank-1.0.3|${key}`]) continue;

            // RESOLVE THROUGH THE REGISTRY, don't guess the id from the field
            // name. parameters.csv already records which upstream feature each
            // card field came from, so `subjectVerbOrder` is WALS 82A and
            // `hasCoreCase` is Grambank GB070. Matching on the field name alone
            // reported 7 features as unexplained whose explainers existed the
            // whole time under `wals-82A`, `wals-20A` and so on — the atlas had
            // renamed the fields and this lookup was still spelling the old
            // ones. Deriving the id from the registry means a future rename
            // cannot break it again.
            const upstream = registryUpstreamFor(key);
            if (upstream && featureIds.has(upstream)) continue;

            missing.add(`typologicalProfile.${key}`);
          }
        }

        // (b) explicit feature IDs cited in _fieldSources
        // (e.g. "wals-45A (Helmbrecht 2013)", "template-generated:grambank-GB415")
        const sourceValues = collectFieldSourceValues(card._fieldSources || {});
        for (const value of sourceValues) {
          if (typeof value !== 'string') continue;
          for (const m of value.matchAll(/\bwals[- ](\d+[A-Z])\b/g)) {
            if (!featureIds.has(`wals-${m[1]}`)) missing.add(`wals-${m[1]}`);
          }
          for (const m of value.matchAll(/\bgrambank-(GB\d+\w*)\b/g)) {
            if (!featureIds.has(`grambank-${m[1]}`)) missing.add(`grambank-${m[1]}`);
          }
        }

        if (missing.size === 0) return null;

        for (const id of missing) {
          context.missingFeatureCounts.set(
            id, (context.missingFeatureCounts.get(id) || 0) + 1
          );
        }
        const list = [...missing];
        const shown = list.slice(0, 3).join(', ');
        const more = list.length > 3 ? ` (+${list.length - 3} more)` : '';
        return `${list.length} feature ID(s) not in tc-features.json: ${shown}${more}`;
      },
    },

    {
      id: 'modality-valid',
      severity: 'error',
      describe: "modality is null/'spoken'/'signed', and Sign Language-family cards are 'signed'",
      // Position 1/2 of docs/LANGUAGE_TAXONOMY.md: exactly two modalities;
      // sign languages must never be silently mislabeled 'spoken' — a wrong
      // 'spoken' on a sign variety is the derivation's expected failure
      // mode, so the Glottolog family assignment cross-checks it here.
      check: (card) => {
        const m = card.modality;
        if (m !== undefined && m !== null && m !== 'spoken' && m !== 'signed') {
          return `modality '${m}' is not one of null|'spoken'|'signed'`;
        }
        if (card.classification?.family === 'Sign Language' && m !== 'signed') {
          return `Glottolog family is 'Sign Language' but modality is '${m}' (expected 'signed')`;
        }
        return null;
      },
    },

    // Data-quality rules from the corruption audit (docs/
    // CARD_DATA_QUALITY_AUDIT.md), exported by fix-card-corruption.mjs
    // so the repair script and the linter can never drift apart.
    ruleNoUrlInTextFields,
    ruleNoPlaceholderStrings,

    // ── Card-integrity rules (R1–R6) ─────────────────────────
    // The "every fact cited" gate: no claim without a supporting source, no
    // collapsed number wearing a source that contradicts it, no run result on
    // a language card, no metric mislabel. Defined in card-integrity-rules.mjs
    // so node --test can exercise them in isolation; receive `context` so R2
    // can reconcile against champollion.db when it is materialized.
    ...cardIntegrityRules,

    // ── Warning-severity rules ───────────────────────────────

    {
      id: 'glossary-coverage',
      severity: 'warning',
      describe: 'Watchlisted technical terms in rendered card text have glossary.json entries (UNKNOWN-TERM)',
      // WHY warning, not error: the watchlist is a curated to-do list of
      // glossary-worthy terms (shared/explainers/term-watchlist.json).
      // A hit means "write a glossary entry", not "the card is broken".
      check: (card) => {
        if (!context.explainers?.watchlistRegex) return null;

        const text = collectRenderedText(card);
        if (!text) return null;

        const regex = context.explainers.watchlistRegex;
        regex.lastIndex = 0;
        const hits = new Set();
        let m;
        while ((m = regex.exec(text)) !== null) {
          hits.add(m[1].toLowerCase());
        }
        if (hits.size === 0) return null;

        for (const h of hits) {
          context.unknownTermCounts.set(h, (context.unknownTermCounts.get(h) || 0) + 1);
        }
        const list = [...hits];
        const shown = list.slice(0, 4).join(', ');
        const more = list.length > 4 ? ` (+${list.length - 4} more)` : '';
        return `UNKNOWN-TERM: ${list.length} watchlisted term(s) without glossary entry: ${shown}${more}`;
      },
    },

    {
      id: 'license-source-resolves',
      severity: 'warning',
      describe: 'Every _fieldSources value and dataSources[] id resolves to an entry in shared/licenses.json',
      // WHY warning, not error: unresolved ids are register GAPS (sources
      // that need a license entry in tc-licenses.json), not card bugs.
      // Cards must not be mass-edited to silence these — the fix is to
      // register the source's license. See docs/LICENSING.md.
      check: (card, filename) => {
        if (!context.licenseRegister) return null;

        const values = new Set(card.dataSources || []);
        collectFieldSourceValues(card._fieldSources || {}, values);

        const unresolved = new Set();
        let malformedCount = 0;
        for (const value of values) {
          if (typeof value !== 'string' || !value) continue;
          const result = resolveSourceValue(value, context.licenseRegister);
          if (!result.ok) {
            if (result.malformed) malformedCount++;
            for (const u of result.unresolved) unresolved.add(u);
          }
        }

        if (unresolved.size === 0) return null;

        // Track per-source-id counts for the summary report
        for (const u of unresolved) {
          context.unresolvedSourceCounts.set(
            u, (context.unresolvedSourceCounts.get(u) || 0) + 1
          );
        }

        const list = [...unresolved];
        const shown = list.slice(0, 3).join(', ');
        const more = list.length > 3 ? ` (+${list.length - 3} more)` : '';
        const malformedNote = malformedCount > 0
          ? ` [${malformedCount} malformed stringified-array value(s)]`
          : '';
        return `${list.length} source id(s) not in shared/licenses.json: ${shown}${more}${malformedNote}`;
      },
    },

    {
      id: 'has-script',
      severity: 'warning',
      describe: 'Card has script field',
      check: (card) => {
        if (!card.script) {
          return 'Missing script field';
        }
        return null;
      },
    },

    {
      id: 'no-todo-in-vitality',
      severity: 'warning',
      describe: 'vitality.speakerCount is not a TODO string',
      check: (card) => {
        const speakerCount = card.vitality?.speakerCount;
        if (typeof speakerCount === 'string' &&
            (speakerCount === 'TODO' || speakerCount.startsWith('TODO:') || speakerCount.startsWith('TODO '))) {
          return `vitality.speakerCount is a TODO: '${speakerCount}'`;
        }
        return null;
      },
    },

    {
      id: 'no-stale-todo',
      severity: 'warning',
      describe: 'No TODO strings in non-TODO-expected fields',
      check: (card) => {
        const todos = findTodoStrings(card);
        // Filter out fields where TODOs are expected
        const staleTodos = todos.filter(t => !TODO_EXPECTED_FIELDS.has(t.path));
        if (staleTodos.length === 0) return null;

        // Report the first stale TODO (we'll aggregate in the summary anyway)
        const first = staleTodos[0];
        const moreCount = staleTodos.length - 1;
        const suffix = moreCount > 0 ? ` (+${moreCount} more)` : '';
        return `TODO string at '${first.path}': '${first.value}'${suffix}`;
      },
    },

    // ── Info-severity rules ──────────────────────────────────

    {
      id: 'method-support-verified',
      severity: 'info',
      describe: 'Method support entries have verification dates',
      check: (card) => {
        if (!card.methodSupport) return null;

        const unverified = [];
        for (const [method, config] of Object.entries(card.methodSupport)) {
          // Only check methods that claim to be supported — unsupported
          // methods don't need verification dates.
          if (config?.supported && !config.verifiedDate) {
            unverified.push(method);
          }
        }

        if (unverified.length === 0) return null;
        return `Supported methods without verifiedDate: ${unverified.join(', ')}`;
      },
    },

  ];
}


// ─── Linting engine ────────────────────────────────────────────

/**
 * @typedef {Object} LintDiagnostic
 * @property {string} ruleId - which rule fired
 * @property {'error'|'warning'|'info'} severity
 * @property {string} filename - the card file that triggered this
 * @property {string} message - human-readable description of the issue
 */

/**
 * Lint a single card file.
 *
 * @param {string} filename - just the filename (e.g., "amh.json")
 * @param {object} card - parsed JSON content
 * @param {Array} rules - array of rule objects
 * @returns {LintDiagnostic[]} array of diagnostics for this card
 */
function lintCard(filename, card, rules, context) {
  const diagnostics = [];

  for (const rule of rules) {
    // Pass context as the 3rd arg so module-defined rules (the card-integrity
    // R1–R6) can reconcile against loaded data; closure-based rules ignore it.
    const message = rule.check(card, filename, context);
    if (message) {
      diagnostics.push({
        ruleId: rule.id,
        severity: rule.severity,
        filename,
        message,
      });
    }
  }

  return diagnostics;
}

/**
 * Structural schema validation for one card (AJV-style, via mini-schema).
 * Returns WARNING diagnostics only — never build-failing. The known corpus-wide
 * `resources` object-shape divergence (migration is post-ACL) is labeled and
 * stays a warning; other structural drift is surfaced the same way.
 *
 * @returns {LintDiagnostic[]}
 */
function schemaValidateCard(filename, card, schema) {
  if (!schema) return [];
  const { valid, errors } = validateSchema(card, schema);
  if (valid) return [];

  // Collapse to at most two warnings per card (the schema/card drift is wide
  // and pre-existing — emitting one diagnostic per deviation would bury the
  // ERROR signal under tens of thousands of rows). resources object-shape stays
  // a SEPARATE id so the post-ACL migration is greppable and explicitly waived.
  const resourcesErrs = errors.filter(e => e.startsWith('$.resources'));
  const otherErrs = errors.filter(e => !e.startsWith('$.resources'));
  const out = [];
  if (otherErrs.length > 0) {
    const shown = otherErrs.slice(0, 2).join('; ');
    const more = otherErrs.length > 2 ? ` (+${otherErrs.length - 2} more)` : '';
    out.push({
      ruleId: 'card-schema-valid',
      severity: 'warning',
      filename,
      message: `${otherErrs.length} schema deviation(s): ${shown}${more}`,
    });
  }
  if (resourcesErrs.length > 0) {
    out.push({
      ruleId: 'card-schema-resources-shape',
      severity: 'warning',
      filename,
      message: `resources object-shape mismatch (${resourcesErrs.length}); migration is post-ACL — warn, not fail`,
    });
  }
  return out;
}


