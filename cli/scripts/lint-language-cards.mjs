/**
 * Load a code set JSON file (NLLB or FLORES format).
 *
 * These files are JSON objects mapping ISO 639-3 codes to full NLLB/FLORES
 * codes (e.g., { "amh": "amh_Ethi", ... }). They also contain a `_meta`
 * key for provenance that we skip during loading.
 *
 * Returns null if the file is missing (caller must handle gracefully),
 * or a Map<iso639_3, fullCode> on success.
 */
function loadCodeSet(filePath, label) {
  if (!fs.existsSync(filePath)) {
    // Return null instead of empty Map so the caller knows the file
    // was missing (vs. present but empty). This distinction matters
    // because we skip rules when the data file isn't available.
    return null;
  }

  try {
    const raw = fs.readFileSync(filePath, 'utf-8');
    const data = JSON.parse(raw);

    // The files use an object format with a `_meta` key for provenance.
    // We build a Map of only the actual language code entries.
    const map = new Map();
    for (const [key, value] of Object.entries(data)) {
      if (key === '_meta') continue; // skip provenance metadata
      map.set(key, value);
    }
    return map;
  } catch (err) {
    // Don't silently swallow parse errors — the data file might be corrupt
    console.error(`  ERROR: Failed to parse ${label}: ${err.message}`);
    return null;
  }
}

/**
 * BCP 47 private-use conlang cards ('x-…', e.g. x-pirate, x-yoda) are
 * register-only constructs deliberately outside ISO 639-3 / Glottolog —
 * identity rules that assume a real ISO languoid do not apply to them.
 */
function isPrivateUseCard(card) {
  return typeof card?.code === 'string' && card.code.startsWith('x-');
}

/**
 * Glottolog-only stubs are Glottolog level=language nodes that never received an
 * ISO 639-3 code (founder scope decision 2026-07-20). They are keyed on their
 * glottocode (`code` = `xxxx9999`, `iso639_3: null`) — the same code-is-a-
 * general-key pattern as the regional-variant and conlang cards. Identity rules
 * that assume an ISO code do not apply to them.
 */
function isGlottologOnlyCard(card) {
  return card?.iso639_3 == null &&
    typeof card?.code === 'string' &&
    /^[a-z0-9]{4}[0-9]{4}$/.test(card.code);
}

/**
 * NLLB-200 codes that the one-code-per-ISO shape of nllb-200-codes.json
 * cannot represent: the model serves some languages in MULTIPLE scripts,
 * so a second full code exists for the same ISO 639-3 key. Verified
 * against the NLLB-200 model card (facebook/nllb-200-distilled-600M
 * language list): Chinese and Yue Chinese ship both Hans/Hant variants.
 * Keep this list minimal and verifiable — it supplements the data file,
 * it does not replace it. (Added 2026-07-07 for cmn-Hant.json.)
 */
const NLLB_SCRIPT_VARIANT_CODES = ['zho_Hant', 'yue_Hant'];

/**
 * Build the set of valid NLLB full codes (e.g., "amh_Ethi", "pam_Latn").
 * This is what cards claim in methodSupport.nllb.code, so we validate
 * against the actual values, not just the keys.
 */
function buildNllbFullCodeSet(nllbMap) {
  if (!nllbMap) return null;
  return new Set([...nllbMap.values(), ...NLLB_SCRIPT_VARIANT_CODES]);
}


// ─── License register (shared/licenses.json) ──────────────────
//
// Every source id referenced by a card (_fieldSources values and
// dataSources[] entries) must resolve to an entry in the monorepo
// license register so we can prove license compliance line-by-line.
//
// The register keys come from tc-licenses.json (the SQLite facts.source
// vocabulary), while cards carry a LATER vocabulary with versioned ids
// ("glottolog-5.3" vs register key "glottolog-5.0"), prefixed ids
// ("lexibank-dyenindoeuropean" vs "dyenindoeuropean"), renamed ids
// ("iso639-3-2024" vs "sil-iso639-3"), and compound "a+b+c" values.
// The resolution chain below is tolerant of exactly those observed
// patterns — and nothing else. Anything that still fails to resolve is
// a genuine register gap (or a card data bug) and gets reported.

/**
 * Load shared/licenses.json. Returns null if missing (rule is skipped),
 * or { sourceKeys, baseIndex, spdxSet } on success.
 */
function loadLicenseRegister(filePath) {
  // Index construction lives in cli/lib/card-source-resolution.mjs alongside
  // the resolution vocabulary it must agree with — two copies of "how a
  // register key is normalised" would drift from each other, and the linter
  // and the license audit would then disagree about which stamps resolve.
  const index = buildRegisterIndex(filePath);
  if (!index && fs.existsSync(filePath)) {
    console.error('  ERROR: Failed to parse shared/licenses.json');
  }
  return index;
}

