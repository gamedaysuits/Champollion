/**
 * lint-language-cards.mjs
 * ────────────────────────────────────────────────────────────────
 * Language Card Linter / Validator
 *
 * Validates all language card JSON files against a set of rules
 * that enforce data quality, consistency, and completeness.
 *
 * WHY THIS EXISTS:
 *   With ~7,900 language cards generated from multiple data sources,
 *   silent data issues accumulate fast. This linter catches problems
 *   like missing classifications, stale TODO strings, invalid NLLB
 *   codes, and filename/code mismatches before they reach consumers.
 *
 * RULES:
 *   Each rule has an ID, severity (error/warning/info), and a check
 *   function. Rules are defined declaratively so adding new ones is
 *   a single object — no plumbing needed.
 *
 * Usage:
 *   node scripts/lint-language-cards.mjs                  # lint all cards
 *   node scripts/lint-language-cards.mjs --lang pam       # lint single card
 *   node scripts/lint-language-cards.mjs --json           # JSON output
 *   node scripts/lint-language-cards.mjs --fix            # auto-fix (future)
 *
 * Exit codes:
 *   0 — no errors (warnings/info are OK)
 *   1 — at least one error found
 *
 * ────────────────────────────────────────────────────────────────
 */

