/**
 * Group diagnostics by severity and print a console-friendly summary.
 *
 * For large card sets, individual-file diagnostics for very common issues
 * (like missing script on thousands of cards) are collapsed into a count
 * to keep the output readable.
 */
function printConsoleSummary(diagnostics, totalCards) {
  const bySeverity = {
    error: diagnostics.filter(d => d.severity === 'error'),
    warning: diagnostics.filter(d => d.severity === 'warning'),
    info: diagnostics.filter(d => d.severity === 'info'),
  };

  console.log('');

  // ── Errors ──
  if (bySeverity.error.length > 0) {
    console.log(`  ERRORS (${bySeverity.error.length.toLocaleString()}):`);
    printDiagnosticGroup(bySeverity.error);
  }

  // ── Warnings ──
  if (bySeverity.warning.length > 0) {
    console.log(`  WARNINGS (${bySeverity.warning.length.toLocaleString()}):`);
    printDiagnosticGroup(bySeverity.warning);
  }

  // ── Info ──
  if (bySeverity.info.length > 0) {
    console.log(`  INFO (${bySeverity.info.length.toLocaleString()}):`);
    printDiagnosticGroup(bySeverity.info);
  }

  // ── Summary line ──
  console.log('');
  console.log(`  SUMMARY: ${bySeverity.error.length.toLocaleString()} errors, ` +
              `${bySeverity.warning.length.toLocaleString()} warnings, ` +
              `${bySeverity.info.length.toLocaleString()} info`);
}

/**
 * Print a group of diagnostics, collapsing common rule violations.
 *
 * WHY: If 5,000 cards are missing the `script` field, listing each one
 * individually makes the output unreadable. Instead, we show the count
 * and list individual files only when there are few violations.
 */
const COLLAPSE_THRESHOLD = 10;

function printDiagnosticGroup(diagnostics) {
  // Group by rule ID
  const byRule = new Map();
  for (const d of diagnostics) {
    if (!byRule.has(d.ruleId)) {
      byRule.set(d.ruleId, []);
    }
    byRule.get(d.ruleId).push(d);
  }

  for (const [ruleId, items] of byRule) {
    if (items.length <= COLLAPSE_THRESHOLD) {
      // Few enough to list individually
      for (const item of items) {
        console.log(`    [${ruleId}] ${item.filename}: ${item.message}`);
      }
    } else {
      // Too many — collapse into a summary line.
      // Show the first few as examples, then the count.
      const exampleCount = 3;
      const examples = items.slice(0, exampleCount);
      console.log(`    [${ruleId}] ${items.length.toLocaleString()} cards — ${items[0].message}`);
      for (const ex of examples) {
        console.log(`      e.g., ${ex.filename}`);
      }
      if (items.length > exampleCount) {
        console.log(`      ... and ${(items.length - exampleCount).toLocaleString()} more`);
      }
    }
  }
}

/**
 * Build a structured JSON report suitable for CI integration.
 */
function buildJsonReport(diagnostics, totalCards, meta, unresolvedSourceCounts = new Map()) {
  const bySeverity = {
    error: diagnostics.filter(d => d.severity === 'error'),
    warning: diagnostics.filter(d => d.severity === 'warning'),
    info: diagnostics.filter(d => d.severity === 'info'),
  };

  return {
    linter: 'lint-language-cards.mjs',
    timestamp: new Date().toISOString(),
    totalCards,
    counts: {
      errors: bySeverity.error.length,
      warnings: bySeverity.warning.length,
      info: bySeverity.info.length,
    },
    pass: bySeverity.error.length === 0,
    dataFiles: meta,
    // source ids referenced by cards that have no shared/licenses.json
    // entry, with the number of cards referencing each (register gaps)
    unresolvedLicenseSources: Object.fromEntries(
      [...unresolvedSourceCounts.entries()].sort((a, b) => b[1] - a[1])
    ),
    diagnostics,
  };
}


// ─── Card schema (structural / AJV-style validation) ──────────
//
// Loaded once and applied to every card via the vendored mini-schema validator
// (the repo ships no ajv). Emits WARNING diagnostics only — structural drift is
// surfaced, never build-failing (the hard ERROR gate is the rule set above).
// The resources object-shape migration is post-ACL, so resources errors are
// explicitly labeled and stay warnings.

function loadCardSchema() {
  if (!fs.existsSync(CARD_SCHEMA_JSON)) return null;
  try {
    return JSON.parse(fs.readFileSync(CARD_SCHEMA_JSON, 'utf-8'));
  } catch (err) {
    console.error(`  ERROR: Failed to parse language-card.schema.json: ${err.message}`);
    return null;
  }
}

