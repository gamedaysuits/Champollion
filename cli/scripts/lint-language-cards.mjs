// ─── ISO 639-3 macrolanguage table (taxonomy rules) ────────────
//
// Active (I_Status 'A') macrolanguage memberships. Drives the
// cross-card taxonomy rules from docs/LANGUAGE_TAXONOMY.md R5:
//   - macrolanguage-members-bijection (hub members[] ↔ member cards)
//   - hub-no-benchmark-linkage (hubs are navigation, never targets)
// Returns null if the tab file is missing (rules are skipped).

function loadMacroTable() {
  if (!fs.existsSync(MACRO_TAB)) return null;
  try {
    const lines = fs.readFileSync(MACRO_TAB, 'utf-8').split('\n').filter(l => l.trim());
    const header = lines[0].split('\t');
    const mCol = header.indexOf('M_Id');
    const iCol = header.indexOf('I_Id');
    const sCol = header.indexOf('I_Status');
    const membersByMacro = new Map();
    for (let i = 1; i < lines.length; i++) {
      const cols = lines[i].split('\t');
      if (cols[sCol]?.trim() !== 'A') continue; // active rows only — 'R' is retired
      const m = cols[mCol]?.trim();
      const member = cols[iCol]?.trim();
      if (!m || !member) continue;
      if (!membersByMacro.has(m)) membersByMacro.set(m, []);
      membersByMacro.get(m).push(member);
    }
    for (const list of membersByMacro.values()) list.sort();
    return membersByMacro;
  } catch (err) {
    console.error(`  ERROR: Failed to parse macrolanguages tab: ${err.message}`);
    return null;
  }
}

/**
 * Cross-card taxonomy checks (docs/LANGUAGE_TAXONOMY.md R5). Runs as a
 * post-pass because the per-card rule API cannot see other cards.
 *
 * @param {Map<string, object>} cardIndex - flat card code → parsed card
 * @param {Map<string, string[]>} membersByMacro - active M-table rows
 * @returns {LintDiagnostic[]}
 */
function lintTaxonomy(cardIndex, membersByMacro) {
  const diagnostics = [];
  const err = (filename, ruleId, message) =>
    diagnostics.push({ ruleId, severity: 'error', filename, message });

  // ── Rule: atlas-version-uniform (corpus-level) ──
  // Every projected card must carry ONE named `_atlas.version`, and never
  // 'unreleased'. The first cutover shipped 'unreleased' onto all 17,360
  // cards, which left requireAtlas() — the designed-in drift tripwire —
  // structurally inert: no consumer can pin a build nobody named. Two
  // distinct versions in one corpus means a half-applied cutover, the exact
  // failure the reader tests could not see while they read build output.
  // genera/ is exempt by charter (hand-authored parents, no _atlas stamp —
  // see genera/README.md); this loop iterates only the projected top-level
  // corpus, so the exemption is structural.
  {
    const byVersion = new Map(); // version → count
    for (const [code, card] of cardIndex) {
      const v = card?._atlas?.version ?? null;
      byVersion.set(v, (byVersion.get(v) ?? 0) + 1);
      if (v === null || v === 'unreleased') {
        err(`${code}.json`, 'atlas-version-uniform',
          `_atlas.version is ${JSON.stringify(v)} — an unnamed build cannot be `
          + 'pinned by requireAtlas(); rebuild with --version and cut over');
      }
    }
    if (byVersion.size > 1) {
      const summary = [...byVersion.entries()]
        .map(([v, n]) => `${JSON.stringify(v)}×${n}`).join(', ');
      err('(corpus)', 'atlas-version-uniform',
        `the corpus carries ${byVersion.size} distinct _atlas.version values `
        + `(${summary}) — a mixed corpus means a half-applied cutover`);
    }
  }

  // Macrolanguage hubs live either as flat scope-M cards (56) or — for
  // the codes purged from flat generation — as genera/macrolanguage-*.json
  // typed hub cards. Collect both.
  const hubs = new Map(); // macro code → { card, filename }
  for (const [code, card] of cardIndex) {
    // ISO 639-3's scope token, in BOTH spellings. The old corpus stored the
    // registry initial ('M'); the atlas records the legible word
    // ('Macrolanguage') by a deliberate decision in parameters.csv. Testing
    // only for 'M' found zero hubs and reported all 800 macrolanguages as
    // missing a hub card that was sitting right there.
    if (card.isoScope === 'M' || card.isoScope === 'Macrolanguage') {
      hubs.set(code, { card, filename: `${code}.json` });
    }
  }
  const generaDir = path.join(CARDS_DIR, 'genera');
  if (fs.existsSync(generaDir)) {
    for (const f of fs.readdirSync(generaDir)) {
      if (!f.startsWith('macrolanguage-') || !f.endsWith('.json')) continue;
      let card;
      try {
        card = JSON.parse(fs.readFileSync(path.join(generaDir, f), 'utf-8'));
      } catch {
        continue; // genera parse errors are out of scope here
      }
      const macro = f.replace('macrolanguage-', '').replace('.json', '');
      if (!hubs.has(macro)) hubs.set(macro, { card, filename: `genera/${f}` });
    }
  }

  // ── Rule: macrolanguage-members-bijection ──
  const memberSetByMacro = new Map();
  for (const [macro, members] of membersByMacro) {
    memberSetByMacro.set(macro, new Set(members));
    const hub = hubs.get(macro);
    if (!hub) {
      err(`${macro}.json`, 'macrolanguage-members-bijection',
        `ISO macrolanguage '${macro}' has no hub card (flat scope-M or genera/macrolanguage-${macro}.json)`);
      continue;
    }
    // `members` was the hub-card field; the atlas projects the same fact as
    // `macrolanguageMembers`, straight from ISO's own M-table. Both read, so
    // the rule holds across the migration.
    const cardMembers = Array.isArray(hub.card.macrolanguageMembers)
      ? hub.card.macrolanguageMembers
      : (Array.isArray(hub.card.members) ? hub.card.members : []);
    const expected = members.join(',');
    const actual = [...cardMembers].sort().join(',');
    if (expected !== actual) {
      err(hub.filename, 'macrolanguage-members-bijection',
        `members[] does not match active M-table rows (expected [${expected}], got [${actual}])`);
    }
    for (const member of members) {
      const memberCard = cardIndex.get(member);
      if (!memberCard) {
        err(hub.filename, 'macrolanguage-members-bijection',
          `member '${member}' has no card file`);
      } else if (memberCard.macrolanguage !== macro) {
        err(`${member}.json`, 'macrolanguage-members-bijection',
          `macrolanguage is '${memberCard.macrolanguage}' but the M-table assigns it to '${macro}'`);
      }
    }
  }
  for (const [code, card] of cardIndex) {
    if (card.macrolanguage == null) continue;
    // A locale is a PROJECTION of its language, so it inherits that language's
    // macrolanguage — `als-AL` carries `sqi` because `als` does. ISO's M-table
    // lists languages, not locales, so asking whether `als-AL` is a member of
    // `sqi` is the wrong question: the membership belongs to the parent, and
    // the parent is checked on its own card.
    if (card.locale?.language) continue;
    const members = memberSetByMacro.get(card.macrolanguage);
    if (!members) {
      err(`${code}.json`, 'macrolanguage-members-bijection',
        `macrolanguage '${card.macrolanguage}' is not an ISO 639-3 macrolanguage`);
    } else if (!members.has(code)) {
      err(`${code}.json`, 'macrolanguage-members-bijection',
        `claims macrolanguage '${card.macrolanguage}' but is not in its active M-table members`);
    }
  }

  // ── Rule: hub-no-benchmark-linkage ──
  // Hub cards are a typed navigation layer, never benchmark targets
  // (Position 4): benchmark/readiness data must live on member cards.
  for (const [macro, { card, filename }] of hubs) {
    if (card.pipelineReadiness != null) {
      err(filename, 'hub-no-benchmark-linkage',
        `macrolanguage hub '${macro}' carries pipelineReadiness — hubs are never benchmark targets`);
    }
    if (Array.isArray(card.evalDatasets) && card.evalDatasets.length > 0) {
      err(filename, 'hub-no-benchmark-linkage',
        `macrolanguage hub '${macro}' lists evalDatasets [${card.evalDatasets.join(', ')}] — benchmarks bind to member languages`);
    }
  }

  return diagnostics;
}

// ─── Explainer layer (shared/explainers/) ─────────────────────
//
// tc-features.json maps every typological feature surfaced on cards to
// a plain-English explainer (name, question, value labels, citation).
// glossary.json defines the technical terms that appear in rendered
// card text. The `explainer-coverage` rule enforces that the card UI
// can always resolve what it shows; `glossary-coverage` watches for
// technical terms that have no glossary entry yet (via a curated
// watchlist — NOT free-text NLP).

/**
 * Load the explainer datasets. Returns null if tc-features.json is
 * missing (rules are skipped), or:
 *   { featureIds, propertyIndex, glossaryVocab, watchlistRegex,
 *     glossaryIntegrityErrors }
 */
function loadExplainers() {
  if (!fs.existsSync(TC_FEATURES_JSON)) return null;

  try {
    const tcFeatures = JSON.parse(fs.readFileSync(TC_FEATURES_JSON, 'utf-8'));
    const featureIds = new Set(Object.keys(tcFeatures.features || {}));
    const propertyIndex = tcFeatures.propertyIndex || {};

    // ── Glossary: build detection vocabulary + check internal links ──
    const glossaryVocab = new Set();
    const glossaryIntegrityErrors = [];
    if (fs.existsSync(GLOSSARY_JSON)) {
      const glossary = JSON.parse(fs.readFileSync(GLOSSARY_JSON, 'utf-8'));
      const termNames = new Set((glossary.terms || []).map(t => t.term));
      for (const t of glossary.terms || []) {
        glossaryVocab.add(t.term.toLowerCase());
        for (const a of t.also || []) glossaryVocab.add(a.toLowerCase());
        // Internal cross-link check: every `related` entry must exist.
        for (const r of t.related || []) {
          if (!termNames.has(r)) {
            glossaryIntegrityErrors.push(
              `glossary term '${t.term}' has dangling related link '${r}'`
            );
          }
        }
      }
    }

    // ── Watchlist: curated UNKNOWN-TERM detection vocabulary ──
    // Only terms in this maintained list trigger warnings; terms already
    // in the glossary are by definition covered.
    let watchlistRegex = null;
    const watchlistTerms = [];
    if (fs.existsSync(TERM_WATCHLIST_JSON)) {
      const watchlist = JSON.parse(fs.readFileSync(TERM_WATCHLIST_JSON, 'utf-8'));
      for (const entry of watchlist.watchlist || []) {
        for (const v of [entry.term, ...(entry.also || [])]) {
          if (!glossaryVocab.has(v.toLowerCase())) {
            watchlistTerms.push({ variant: v, canonical: entry.term });
          }
        }
      }
      if (watchlistTerms.length > 0) {
        // One compiled regex over all variants; word-boundary anchored
        // so 'paucal' doesn't fire inside an unrelated longer word.
        const escaped = watchlistTerms
          .map(t => t.variant.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
          .sort((a, b) => b.length - a.length);
        watchlistRegex = new RegExp(`\\b(${escaped.join('|')})\\b`, 'gi');
      }
    }

    return { featureIds, propertyIndex, glossaryVocab, watchlistRegex, watchlistTerms, glossaryIntegrityErrors };
  } catch (err) {
    console.error(`  ERROR: Failed to parse explainer data: ${err.message}`);
    return null;
  }
}

