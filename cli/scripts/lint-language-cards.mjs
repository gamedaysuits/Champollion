/**
 * Collect the rendered text fields of a card that end-users actually
 * see — the harvest surface for glossary-coverage. Mirrors the field
 * set used to curate glossary.json. Keep the two in sync.
 */
function collectRenderedText(card) {
  const chunks = [];
  if (card.linguisticChallenges) {
    for (const v of Object.values(card.linguisticChallenges)) {
      if (typeof v === 'string') chunks.push(v);
    }
  }
  for (const key of ['gender', 'formality', 'codeSwitching', 'orthographicStatus', 'dialectInfo']) {
    const o = card[key];
    if (typeof o === 'string') chunks.push(o);
    else if (o && typeof o === 'object') {
      for (const v of Object.values(o)) if (typeof v === 'string') chunks.push(v);
    }
  }
  if (card.encyclopedic && typeof card.encyclopedic === 'object') {
    for (const v of Object.values(card.encyclopedic)) {
      if (typeof v === 'string') chunks.push(v);
    }
  }
  if (typeof card.notes === 'string') chunks.push(card.notes);
  return chunks.join(' ');
}

/**
 * Collect every string value in a card's _fieldSources map (values can
 * be nested objects/arrays of strings keyed by field path).
 */
function collectFieldSourceValues(obj, out = new Set()) {
  if (typeof obj === 'string') {
    out.add(obj);
  } else if (Array.isArray(obj)) {
    for (const item of obj) collectFieldSourceValues(item, out);
  } else if (obj && typeof obj === 'object') {
    for (const value of Object.values(obj)) collectFieldSourceValues(value, out);
  }
  return out;
}


