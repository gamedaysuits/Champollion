/**
 * card field (last path segment) → its explainer feature id, read from the
 * parameter registry rather than guessed from the field's name.
 *
 * `Upstream_Parameter_ID` is where the build already records that
 * typologicalProfile.subjectVerbOrder is WALS 82A; `Sources` says which
 * catalogue, which gives the `wals-`/`grambank-` prefix the explainer index
 * uses. Returns undefined for anything the registry does not map, so an
 * unmapped field still reports as a gap.
 */
let _registryUpstream = null;
function registryUpstreamFor(field) {
  if (_registryUpstream === null) {
    _registryUpstream = new Map();
    try {
      const csv = path.join(CLI_ROOT, '..', 'shared', 'cldf', 'parameters.csv');
      const { rows } = parseCSVObjects(fs.readFileSync(csv, 'utf-8'), { file: 'parameters.csv' });
      for (const r of rows) {
        if (!r.Upstream_Parameter_ID || !r.Card_Field) continue;
        const leaf = r.Card_Field.split('.').pop();
        const cat = /grambank/i.test(r.Sources ?? '') ? 'grambank'
          : /wals/i.test(r.Sources ?? '') ? 'wals' : null;
        if (cat) _registryUpstream.set(leaf, `${cat}-${r.Upstream_Parameter_ID}`);
      }
    } catch { /* registry unreadable — every field simply stays unmapped */ }
  }
  return _registryUpstream.get(field);
}
