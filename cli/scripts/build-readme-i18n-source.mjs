#!/usr/bin/env node
/**
 * build-readme-i18n-source.mjs — regenerate the README translation source.
 *
 * cli/README.md is the single source of truth for the README. This script
 * derives cli/docs/README.en.md from it (the content-sync input whose
 * siblings become docs/README.<locale>.md), applying two transforms:
 *
 *   1. Strip the translation banner (the block between the
 *      readme-i18n-banner markers). The banner's links are relative to
 *      cli/, so inside docs/ they would be broken — and a French reader
 *      of docs/README.fr.md doesn't need a link to the French README.
 *
 *   2. Rewrite relative markdown links with a `../` prefix so they still
 *      resolve from docs/ (e.g. website/docs/... → ../website/docs/...).
 *      Absolute URLs, #anchors, and mailto: are left untouched.
 *
 * docs/README.en.md is gitignored — it is build input, regenerated by the
 * pre-push gate (scripts/champollion_sync_gate.sh) before every sync, so it
 * can never drift from README.md the way the old README-source.md fork did.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const cliRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readmePath = path.join(cliRoot, 'README.md');
const outPath = path.join(cliRoot, 'docs', 'README.en.md');

let src = fs.readFileSync(readmePath, 'utf-8');

// 1. Strip the banner block (inclusive of its marker comments).
src = src.replace(
  /<!-- readme-i18n-banner-start -->[\s\S]*?<!-- readme-i18n-banner-end -->\n?/,
  ''
);

// 2. Prefix relative link/image targets with ../ (skip absolute, anchor,
//    mailto, protocol-relative, and already-parent-relative targets).
src = src.replace(/(\]\()([^)\s]+)(\))/g, (m, open, target, close) => {
  if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|#|\.\.\/)/i.test(target)) return m;
  return `${open}../${target}${close}`;
});

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, src, 'utf-8');
console.log(`readme-i18n source: wrote ${path.relative(cliRoot, outPath)} (${src.length} chars)`);
