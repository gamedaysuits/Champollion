# Cross-implementation parity (seal.mjs → Python).
# ---------------------------------------------------------------------------

class TestSealMjsParity:
    def test_node_sealed_artifact_opens_in_python(self):
        artifact = json.loads((FIXTURES / "parity.sealed.json").read_text())
        want = (FIXTURES / "parity.plaintext.json").read_text().rstrip("\n")
        got = ts.open_sealed(artifact, _fixture_scalar()).decode("utf-8")
        assert got == want

    def test_key_id_recipe_matches(self):
        key = json.loads((FIXTURES / "parity.key.json").read_text())
        der = base64.b64decode(key["publicKeyDerB64"])
        assert ts.key_id_for_spki_der(der) == key["keyId"]

    def test_node_signature_verifies_in_python(self):
        payload = (FIXTURES / "parity.sign-payload.json").read_bytes()
        sig = json.loads((FIXTURES / "parity.sig.json").read_text())
        pub = json.loads((FIXTURES / "parity.sign.pub.json").read_text())
        assert sig["scheme"] == ts.SIGN_SCHEME
        assert ts.verify_payload(payload, sig["signatureB64"],
                                 base64.b64decode(pub["publicKeyDerB64"]))

    def test_shamir_split_scalar_still_opens_node_artifact(self):
        """The custody upgrade in one assertion: split the fixture's private
        scalar 3-of-5, reconstruct from a quorum, open the seal.mjs-sealed
        artifact — the FORMAT never changed, only who holds the key."""
        artifact = json.loads((FIXTURES / "parity.sealed.json").read_text())
        shares = split(_fixture_scalar(), 5, 3)
        with SecretBuffer(combine([shares[1], shares[3], shares[4]])) as key:
            got = ts.open_sealed(artifact, key.bytes())
        assert b"synthetic" in got or b"SYN-" in got


class TestReverseParity:
    """Python → Node: the OTHER direction the static fixtures never covered.
    Python seals/signs, then the champollion CLI (seal.mjs) opens/verifies —
    closing the 'either CLI verifies the other's output' claim. Skips cleanly
    where node / the cli tree is absent (the Phase-A pattern)."""

    def _cli(self):
        import shutil
        if shutil.which("node") is None:
            pytest.skip("node not available for the reverse parity check")
        try:
            from mt_eval_harness.contest_prep import find_champollion_cli
            return find_champollion_cli()
        except Exception:
            pytest.skip("champollion CLI not resolvable in this tree")

    def test_python_seal_opens_in_node(self, tmp_path):
        import subprocess
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric import x25519
        cli = self._cli()

        priv = x25519.X25519PrivateKey.generate()
        scalar = priv.private_bytes(serialization.Encoding.Raw,
                                    serialization.PrivateFormat.Raw,
                                    serialization.NoEncryption())
        pub_der = ts.derive_x25519_public_spki_der(scalar)
        priv_der = priv.private_bytes(serialization.Encoding.DER,
                                      serialization.PrivateFormat.PKCS8,
                                      serialization.NoEncryption())
        plaintext = b'[{"source": "reverse synthetic", "target": "SYN-rev"}]'
        aad = ts.build_aad("eval-reverse-v1", "grp-rev")
        sealed = ts.seal_bytes(plaintext, pub_der, aad)
        artifact = ts.build_sealed_artifact(
            sealed, card_id="eval-reverse-v1", custodian_group_id="grp-rev")
        art_f = tmp_path / "artifact.sealed.json"
        art_f.write_text(json.dumps(artifact), encoding="utf-8")
        key_f = tmp_path / "recipient.key.json"
        key_f.write_text(json.dumps({
            "publicKeyDerB64": base64.b64encode(pub_der).decode(),
            "privateKeyDerB64": base64.b64encode(priv_der).decode(),
            "keyId": ts.key_id_for_spki_der(pub_der)}), encoding="utf-8")
        out_f = tmp_path / "opened.json"
        proc = subprocess.run(
            cli + ["seal-corpus", "open", "--artifact", str(art_f),
                   "--privkey", str(key_f), "--out", str(out_f)],
            capture_output=True, text=True, timeout=120)
        assert proc.returncode == 0, proc.stderr or proc.stdout
        assert out_f.read_bytes() == plaintext

    def test_python_signature_verifies_in_node(self, tmp_path):
        import subprocess
        cli = self._cli()

        pair = ts.generate_signing_keypair()
        payload = b'{"scores":{"chrf":12.5},"synthetic":true}'
        payload_f = tmp_path / "payload.json"
        payload_f.write_bytes(payload)
        block = ts.sign_payload(payload,
                                base64.b64decode(pair["privateKeyDerB64"]))
        sig_f = tmp_path / "sig.json"
        sig_f.write_text(json.dumps(block), encoding="utf-8")
        pub_f = tmp_path / "sign.pub.json"
        pub_f.write_text(json.dumps(
            {"publicKeyDerB64": pair["publicKeyDerB64"],
             "keyId": pair["keyId"]}), encoding="utf-8")
        proc = subprocess.run(
            cli + ["seal-corpus", "verify", "--payload", str(payload_f),
                   "--sig", str(sig_f), "--pubkey", str(pub_f)],
            capture_output=True, text=True, timeout=120)
        assert proc.returncode == 0, proc.stderr or proc.stdout


