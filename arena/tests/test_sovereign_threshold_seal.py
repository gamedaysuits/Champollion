class TestPythonSealOpen:
    def _sealed(self, plaintext=b'{"synthetic": true}'):
        scalar = secrets.token_bytes(32)
        pub = ts.derive_x25519_public_spki_der(scalar)
        aad = ts.build_aad("eval-x-v1", "group-x")
        return scalar, ts.seal_bytes(plaintext, pub, aad)

    def test_roundtrip(self):
        scalar, sealed = self._sealed(b"synthetic plaintext 123")
        assert sealed["cipher"] == ts.SEAL_CIPHER
        assert ts.open_sealed(sealed, scalar) == b"synthetic plaintext 123"

    def test_wrong_key_refused(self):
        _, sealed = self._sealed()
        with pytest.raises(ts.ThresholdSealError, match="wrong key|tampered"):
            ts.open_sealed(sealed, secrets.token_bytes(32))

    def test_tampered_ciphertext_refused(self):
        scalar, sealed = self._sealed()
        ct = bytearray(base64.b64decode(sealed["ciphertext"]))
        ct[0] ^= 0xFF
        sealed["ciphertext"] = base64.b64encode(bytes(ct)).decode()
        with pytest.raises(ts.ThresholdSealError,
                           match="integrity|digest"):
            ts.open_sealed(sealed, scalar)

    def test_wrong_aad_refused(self):
        scalar, sealed = self._sealed()
        with pytest.raises(ts.ThresholdSealError):
            ts.open_sealed(sealed, scalar,
                           aad=ts.build_aad("eval-OTHER-v1", "group-x"))

    def test_unknown_cipher_refused(self):
        scalar, sealed = self._sealed()
        sealed["cipher"] = "rot13-hope"
        with pytest.raises(ts.ThresholdSealError, match="cipher"):
            ts.open_sealed(sealed, scalar)

    def test_empty_plaintext_refused(self):
        with pytest.raises(ts.ThresholdSealError, match="empty"):
            self._sealed(b"")

    def test_card_block_has_exact_schema_fields(self):
        _, sealed = self._sealed()
        block = ts.build_sealed_card_block(
            sealed, custodian_group_id="group-x",
            key_scheme="shamir-gf256-3-of-5")
        assert set(block) == {"cipher", "custodianGroupId",
                              "ciphertextDigest", "aad", "thresholdKeyId",
                              "keyScheme", "qualifierId",
                              "qualifierThreshold", "artifactRef"}
        # The schema's required four are populated.
        for req in ("cipher", "custodianGroupId", "ciphertextDigest", "aad"):
            assert block[req]


class TestSealCorpusToArtifact:
    def test_writes_artifact_and_card_block(self, tmp_path):
        corpus = tmp_path / "c.json"
        corpus.write_text('[{"source": "syn", "target": "syn-t"}]')
        scalar = secrets.token_bytes(32)
        pub_b64 = base64.b64encode(
            ts.derive_x25519_public_spki_der(scalar)).decode()
        pub_file = tmp_path / "pub.json"
        pub_file.write_text(json.dumps({
            "publicKeyDerB64": pub_b64, "keyScheme": "shamir-gf256-3-of-5"}))
        out = ts.seal_corpus_to_artifact(
            corpus, pub_file, card_id="eval-a-v1",
            custodian_group_id="grp", out_dir=tmp_path / "sealed")
        artifact = json.loads(Path(out["artifact_path"]).read_text())
        block = json.loads(Path(out["block_path"]).read_text())
        assert artifact["champollionSealed"] == ts.SEAL_VERSION
        assert artifact["cardId"] == "eval-a-v1"
        assert "source" not in artifact.get("ciphertext", "")[:0]  # shape only
        assert block["keyScheme"] == "shamir-gf256-3-of-5"
        # And the artifact opens back to the corpus bytes.
        assert ts.open_sealed(artifact, scalar) == corpus.read_bytes()
        # No plaintext token in either written file.
        for p in (out["artifact_path"], out["block_path"]):
            assert b"syn-t" not in Path(p).read_bytes()


class TestSigning:
    def test_sign_verify_roundtrip_and_tamper(self):
        pair = ts.generate_signing_keypair()
        priv = base64.b64decode(pair["privateKeyDerB64"])
        pub = base64.b64decode(pair["publicKeyDerB64"])
        block = ts.sign_payload(b"scores-bytes", priv)
        assert block["scheme"] == ts.SIGN_SCHEME
        assert block["keyId"] == pair["keyId"]
        assert ts.verify_payload(b"scores-bytes", block["signatureB64"], pub)
        assert not ts.verify_payload(b"scores-bytes!",
                                     block["signatureB64"], pub)

    def test_load_key_material_prefers_the_wanted_half(self, tmp_path):
        pair = ts.generate_signing_keypair()
        f = tmp_path / "k.key.json"
        f.write_text(json.dumps(pair))
        assert ts.load_key_material(f, want="public") == base64.b64decode(
            pair["publicKeyDerB64"])
        assert ts.load_key_material(f, want="private") == base64.b64decode(
            pair["privateKeyDerB64"])
        pub_only = tmp_path / "k.pub.json"
        pub_only.write_text(json.dumps(
            {"publicKeyDerB64": pair["publicKeyDerB64"]}))
        with pytest.raises(ts.ThresholdSealError, match="privateKeyDerB64"):
            ts.load_key_material(pub_only, want="private")


class TestSecretBuffer:
    def test_zero_on_close_and_source_zeroed(self):
        src = bytearray(b"\xaa" * 32)
        buf = SecretBuffer(src)
        assert src == bytearray(32)          # caller's copy scrubbed
        assert buf.bytes() == b"\xaa" * 32
        buf.close()
        assert buf.closed
        with pytest.raises(RuntimeError):
            buf.bytes()
        buf.close()                          # idempotent

    def test_context_manager_and_repr_never_leak(self):
        with SecretBuffer(b"\x01" * 32) as buf:
            assert len(buf) == 32
            assert "\\x01" not in repr(buf) and "01" * 8 not in repr(buf)
        assert buf.closed

    def test_empty_refused(self):
        with pytest.raises(ValueError):
            SecretBuffer(b"")
