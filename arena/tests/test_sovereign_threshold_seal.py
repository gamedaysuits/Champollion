"""threshold_seal — Python↔seal.mjs format parity + refusal edges.

The parity fixtures under fixtures/sovereign/ were generated by seal.mjs
itself (throwaway keys, synthetic sentences): if the Python open ever
drifts from the Node seal, these tests fail — the two implementations are
pinned to ONE envelope format. SecretBuffer hygiene is covered here too.
"""

from __future__ import annotations

import base64
import json
import secrets
from pathlib import Path

import pytest

pytest.importorskip(
    "cryptography",
    reason="sovereign threshold lane needs the cryptography library "
           "(pip install 'mt-eval[node]')")

from mt_eval_harness.sovereign import threshold_seal as ts
from mt_eval_harness.sovereign.secret_buffer import SecretBuffer
from mt_eval_harness.sovereign.shamir_gf256 import combine, split

FIXTURES = Path(__file__).parent / "fixtures" / "sovereign"


def _fixture_scalar() -> bytes:
    from cryptography.hazmat.primitives import serialization
    key = json.loads((FIXTURES / "parity.key.json").read_text())
    priv = serialization.load_der_private_key(
        base64.b64decode(key["privateKeyDerB64"]), password=None)
    return priv.private_bytes(serialization.Encoding.Raw,
                              serialization.PrivateFormat.Raw,
                              serialization.NoEncryption())


