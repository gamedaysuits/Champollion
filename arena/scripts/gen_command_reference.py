#!/usr/bin/env python3
"""Generate the mt-eval command reference from the argparse parser itself.

Single source of truth: the reference page is DERIVED from
``mt_eval_harness.cli.build_parser()``, so it cannot drift from the real
commands and flags (the same idea as ``forge/scripts/gen_command_reference.py``
for nmt-forge). Run after any CLI change, from the repo root or anywhere:

    python3 arena/scripts/gen_command_reference.py           # write the page
    python3 arena/scripts/gen_command_reference.py --check   # exit 3 if stale
    python3 arena/scripts/gen_command_reference.py --stdout  # print, write nothing

Default output: ``cli/website/docs/reference/mt-eval.md`` (served at
/docs/reference/mt-eval).

Exit codes (the site builders' contract — build-llms-full.mjs,
build-for-agents-md.mjs): 0 = written / current, 3 = the committed page is
STALE (regenerate and commit it), 1 = the generator itself failed (not
staleness — regenerating will not fix it).

What the page holds: the global flags once; then every subcommand (and every
nested subcommand — ``contest``, ``node``, ``node ceremony``, ``shared-task``,
``project``) with its help line, its description and epilog, a table of its
arguments, and a table of its options. The two global flags (``--json``,
``--non-interactive``) that ``_share_global_flags`` copies onto every
subparser are listed once, not repeated under every command. Bare ``mt-eval``
with no subcommand runs ``mt-eval run``, so the main parser's copy of the run
flags is not listed twice either.

The page reflects parser structure only — no corpus data, no machine paths.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ARENA_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = ARENA_ROOT.parent
# The arena checkout always wins over any installed mt-eval-harness, so the
# page describes THIS tree's parser, never a stale site-packages copy.
if str(ARENA_ROOT) not in sys.path:
    sys.path.insert(0, str(ARENA_ROOT))

from mt_eval_harness.cli import build_global_parser, build_parser  # noqa: E402

DEFAULT_OUT = REPO_ROOT / "cli" / "website" / "docs" / "reference" / "mt-eval.md"
REGEN = "python3 arena/scripts/gen_command_reference.py"

FRONT_MATTER = f"""---
title: mt-eval command reference
sidebar_label: mt-eval
slug: /reference/mt-eval
description: Every mt-eval subcommand, argument and option — generated from the harness's own argument parser, so it never drifts from the tool.
---

<!-- GENERATED by arena/scripts/gen_command_reference.py from
     mt_eval_harness.cli.build_parser() — do not edit by hand.
     Regenerate after any CLI change:  {REGEN}
     Staleness check (exit 3), run by arena/tests/test_gen_command_reference.py:
       {REGEN} --check -->

# mt-eval command reference

`mt-eval` is the evaluation harness. It runs a translation method over a set of
sentences, scores what came back, and keeps the record of the run (its run card).
The same pipeline translates source-only input (`translate`) and serves a method
behind the `/translate` contract (`serve`). It also drives sealed contests
(`contest`, `node`, `shared-task`) and the Join-a-project lane (`project`).

Install it with `python3 -m pip install mt-eval-harness` (Python 3.11 or newer).
Every command below prints its own help with `--help`.

This page is generated from the harness's own argument parser, so every command
and flag on it exists exactly as written.

"""


# ── helpers ─────────────────────────────────────────────────────────────────


def _subparsers_action(parser: argparse.ArgumentParser):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


_CODE_SPAN = re.compile(r"(`[^`]*`)")


def _escape_md(text: str) -> str:
    """Escape what CommonMark would misread OUTSIDE `code` spans: `<word …>`
    parses as a raw HTML tag, a stray `*` as emphasis. Inside a code span the
    text is literal (an entity there would show as `&lt;`), so it is kept."""
    parts = _CODE_SPAN.split(text)
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "&lt;").replace("*", "\\*")
    return "".join(parts)


def _cell(text) -> str:
    """Make one markdown table cell: one line, no raw HTML tags, no pipes."""
    s = " ".join(str(text or "").split())
    return _escape_md(s).replace("|", "\\|")


def _prose(text: str) -> str:
    """A help/description paragraph as markdown prose (keeps `code` spans)."""
    return _escape_md(" ".join(text.split()))


def _help(action: argparse.Action, parser: argparse.ArgumentParser) -> str:
    """The action's help with %(default)s-style specifiers expanded exactly as
    `--help` expands them."""
    if not action.help:
        return ""
    formatter = parser._get_formatter()
    try:
        return formatter._expand_help(action)
    except (KeyError, TypeError, ValueError):
        return action.help


def _takes(action: argparse.Action, parser: argparse.ArgumentParser) -> str:
    """What the option takes: a switch, a choice, or a value (its metavar)."""
    if action.nargs == 0:
        return "switch"
    if action.choices is not None and action.metavar is None:
        return "one of: " + ", ".join(f"`{c}`" for c in action.choices)
    formatter = parser._get_formatter()
    default_metavar = action.dest.upper()
    shown = formatter._format_args(action, default_metavar)
    return f"`{shown}`"


def _default(action: argparse.Action) -> str:
    if action.nargs == 0:
        return ""  # a switch: its default is "off"
    d = action.default
    if d is None or d is argparse.SUPPRESS or d == "" or d == []:
        return ""
    return f"`{d}`"


def _positional_name(action: argparse.Action) -> str:
    name = action.metavar if isinstance(action.metavar, str) else action.dest
    if action.nargs in ("+", argparse.ONE_OR_MORE):
        return f"{name} …"
    if action.nargs in ("*", argparse.ZERO_OR_MORE):
        return f"[{name} …]"
    if action.nargs in ("?", argparse.OPTIONAL):
        return f"[{name}]"
    return name


def _global_flags() -> dict[str, str]:
    """option string → help, for the flags every subcommand inherits."""
    out = {}
    for action in build_global_parser()._actions:
        for opt in action.option_strings:
            out[opt] = action.help or ""
    return out


GLOBAL_FLAGS = _global_flags()


def _is_inherited_global(action: argparse.Action) -> bool:
    return bool(action.option_strings) and all(
        o in GLOBAL_FLAGS and GLOBAL_FLAGS[o] == (action.help or "")
        for o in action.option_strings)


def _render_block(text: str, raw: bool, lines: list[str]) -> None:
    """A description or epilog. Paragraphs are split on blank lines; under a
    raw formatter an indented/columned paragraph keeps its layout in a text
    fence."""
    for para in text.strip().split("\n\n"):
        para = para.rstrip()
        if not para.strip():
            continue
        if raw and "\n" in para.strip():
            lines.append("```text")
            lines.append(para.strip("\n"))
            lines.append("```")
        else:
            lines.append(_prose(para))
        lines.append("")


# ── rendering ───────────────────────────────────────────────────────────────


def _render_parser(path: str, parser: argparse.ArgumentParser, help_line: str,
                   level: int, lines: list[str]) -> None:
    lines.append(f"{'#' * level} `{path}`")
    lines.append("")
    raw = issubclass(parser.formatter_class, argparse.RawDescriptionHelpFormatter)
    if help_line:
        lines.append(_prose(help_line))
        lines.append("")
    if parser.description and " ".join(parser.description.split()) != " ".join(
            (help_line or "").split()):
        _render_block(parser.description, raw, lines)

    positionals, optionals = [], []
    sub = None
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            sub = action
            continue
        if isinstance(action, argparse._HelpAction):
            continue
        if action.help == argparse.SUPPRESS:
            continue
        if _is_inherited_global(action):
            continue
        (optionals if action.option_strings else positionals).append(action)

    if positionals:
        lines.append("| Argument | Description |")
        lines.append("|---|---|")
        for a in positionals:
            lines.append(f"| `{_positional_name(a)}` | {_cell(_help(a, parser))} |")
        lines.append("")
    if optionals:
        lines.append("| Option | Takes | Default | Description |")
        lines.append("|---|---|---|---|")
        for a in optionals:
            flags = ", ".join(f"`{s}`" for s in a.option_strings)
            desc = _cell(_help(a, parser))
            if a.required:
                desc = ("**Required.** " + desc).strip()
            lines.append(f"| {flags} | {_cell(_takes(a, parser))} | "
                         f"{_cell(_default(a))} | {desc} |")
        lines.append("")
    if not positionals and not optionals and sub is None:
        lines.append("No options beyond the global flags.")
        lines.append("")

    if parser.epilog:
        _render_block(parser.epilog, raw, lines)

    if sub is not None:
        helps = {act.dest: act.help or "" for act in sub._choices_actions}
        names = list(sub.choices)
        lines.append("Subcommands: " + ", ".join(
            f"[`{n}`](#{_anchor(f'{path} {n}')})" for n in names) + ".")
        lines.append("")
        for name, subparser in sub.choices.items():
            _render_parser(f"{path} {name}", subparser, helps.get(name, ""),
                           min(level + 1, 6), lines)


def _anchor(heading: str) -> str:
    """Docusaurus' heading id for a `code` heading: lower-case, spaces → '-',
    punctuation other than '-'/'_' dropped."""
    out = []
    for ch in heading.lower():
        if ch.isalnum() or ch in "-_":
            out.append(ch)
        elif ch == " ":
            out.append("-")
    return "".join(out)


CLI_JS = REPO_ROOT / "cli" / "bin" / "cli.js"


def _network_commands() -> list[str]:
    """The champollion commands grouped under `champollion network`, read from
    the CLI's own COMMAND_GROUPS (cli/bin/cli.js) — never a copied list."""
    src = CLI_JS.read_text(encoding="utf-8")
    m = re.search(r"const COMMAND_GROUPS = \{[\s\S]*?network:\s*\[([^\]]*)\]", src)
    if not m:
        raise RuntimeError(f"no COMMAND_GROUPS.network in {CLI_JS}")
    return re.findall(r"'([\w-]+)'", m.group(1))


def _grouped(text: str) -> str:
    """The docs write champollion's network commands in their grouped form
    (`champollion network seal-corpus`), the one the CLI reference and the
    round-5 docs rule use; the harness's help sometimes names the bare alias
    (`champollion seal-corpus`), which runs the same command."""
    names = "|".join(re.escape(n) for n in _network_commands())
    return re.sub(rf"\bchampollion (?!network )({names})\b", r"champollion network \1", text)


def generate() -> str:
    parser = build_parser()
    lines: list[str] = [FRONT_MATTER]

    # Global flags, once.
    lines.append("## Global flags")
    lines.append("")
    lines.append("These work before or after any subcommand, at any depth "
                 "(`mt-eval --json test run.json` and `mt-eval test run.json --json` "
                 "are the same).")
    lines.append("")
    lines.append("| Option | Description |")
    lines.append("|---|---|")
    for action in parser._actions:
        if not action.option_strings or isinstance(action, argparse._HelpAction):
            continue
        if action.option_strings[0] in GLOBAL_FLAGS or isinstance(
                action, argparse._VersionAction):
            flags = ", ".join(f"`{s}`" for s in action.option_strings)
            lines.append(f"| {flags} | {_cell(_help(action, parser))} |")
    lines.append("| `-h`, `--help` | Show the help for `mt-eval` or for any subcommand, and exit. |")
    lines.append("")
    lines.append("Option names are never abbreviated: `--mod` does not mean `--model`.")
    lines.append("")
    lines.append("`mt-eval` with no subcommand runs [`mt-eval run`](#mt-eval-run) "
                 "and takes the same options.")
    lines.append("")

    sub = _subparsers_action(parser)
    if sub is None:
        raise RuntimeError("mt-eval parser has no subcommands")
    helps = {act.dest: act.help or "" for act in sub._choices_actions}

    lines.append("## Commands")
    lines.append("")
    lines.append("| Command | What it does |")
    lines.append("|---|---|")
    for name in sub.choices:
        lines.append(f"| [`mt-eval {name}`](#{_anchor(f'mt-eval {name}')}) | "
                     f"{_cell(helps.get(name, ''))} |")
    lines.append("")

    for name, subparser in sub.choices.items():
        _render_parser(f"mt-eval {name}", subparser, helps.get(name, ""), 2, lines)

    return _grouped("\n".join(lines).rstrip() + "\n")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Generate the mt-eval command reference page.")
    p.add_argument("--out", type=Path, default=DEFAULT_OUT,
                   help=f"where the page goes (default: {DEFAULT_OUT.relative_to(REPO_ROOT)})")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true",
                      help="write nothing; exit 3 if the committed page is stale")
    mode.add_argument("--stdout", action="store_true",
                      help="print the page instead of writing it")
    args = p.parse_args(argv)

    try:
        text = generate()
    except Exception as exc:  # the generator failed — not staleness
        print(f"gen_command_reference: {exc}", file=sys.stderr)
        return 1

    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        committed = args.out.read_text(encoding="utf-8") if args.out.exists() else None
        if committed != text:
            print(f"{args.out.relative_to(REPO_ROOT) if args.out.is_relative_to(REPO_ROOT) else args.out} "
                  f"is stale (the mt-eval parser changed). Regenerate: {REGEN}",
                  file=sys.stderr)
            return 3
        print("mt-eval command reference is current.", file=sys.stderr)
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({text.count(chr(10))} lines)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
