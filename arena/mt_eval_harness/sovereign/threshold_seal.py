"""threshold_seal — the seal.mjs envelope, in Python, for the quorum lane.

FORMAT AUTHORITY: ``cli/lib/seal.mjs`` defines the sealed-artifact envelope
(`x25519-hkdf-sha256+aes-256-gcm`, version '1') and the Ed25519 signature
block (`ed25519-single-node-wave1`). This module implements the SAME formats
in Python — verified byte-for-byte by the cross-implementation parity tests
(tests/test_sovereign_threshold_seal.py, fixtures generated by seal.mjs
itself) — because the quorum lane cannot shell out to a subprocess with the
key as a file: the reconstructed set key exists only in a
:class:`~mt_eval_harness.sovereign.secret_buffer.SecretBuffer` in THIS
process, and dies with the run context. Exactly the seam seal.mjs documents
("WAVE-2 SEAM … the ciphertext format and the card block do NOT change"):
the ceremony changes WHO holds the private half, never the envelope.

Everything cryptographic comes from the ``cryptography`` library (X25519,
HKDF-SHA256, AES-256-GCM, Ed25519). Nothing here invents a primitive.
"""

from __future__ import annotations

import base64
import hashlib
import json
import os
from pathlib import Path

__all__ = [
    "SEAL_CIPHER", "SEAL_VERSION", "SIGN_SCHEME", "ThresholdSealError",
    "build_aad", "key_id_for_spki_der", "derive_x25519_public_spki_der",
    "seal_bytes", "open_sealed", "build_sealed_artifact",
    "build_sealed_card_block",
    "generate_signing_keypair", "sign_payload", "verify_payload",
    "load_key_material",
]

# Mirrors of the seal.mjs constants — bump ONLY in lockstep with seal.mjs.
SEAL_CIPHER = "x25519-hkdf-sha256+aes-256-gcm"
SEAL_VERSION = "1"
SIGN_SCHEME = "ed25519-single-node-wave1"

_HKDF_INFO_PREFIX = b"champollion-sealed-corpus"
_AES_KEY_BYTES = 32
_GCM_IV_BYTES = 12
_GCM_TAG_BYTES = 16
_HKDF_SALT_BYTES = 16


class ThresholdSealError(RuntimeError):
    """A seal/open/sign/verify step that must not proceed — with the reason."""


def _require_cryptography():
    try:
        from cryptography.hazmat.primitives.asymmetric import x25519  # noqa: F401
    except ImportError as exc:  # pragma: no cover - environment-dependent
        raise ThresholdSealError(
            "The sovereign-eval threshold lane needs the 'cryptography' "
            "library. Install it with: pip install 'mt-eval[node]' "
            "(or: pip install cryptography)") from exc


# ---------------------------------------------------------------------------
# AAD + key identity (seal.mjs buildAad / thresholdKeyId).
# ---------------------------------------------------------------------------

def build_aad(card_id: str, custodian_group_id: str) -> str:
    """Deterministic AAD binding a ciphertext to its card + custodian group
    (identical recipe to seal.mjs buildAad)."""
    cid = str(card_id or "").strip()
    group = str(custodian_group_id or "").strip()
    return f"champollion-sealed:v{SEAL_VERSION}|card={cid}|group={group}"


def key_id_for_spki_der(spki_der: bytes) -> str:
    """sha256(SPKI DER)[:16] — the stable short key id seal.mjs stamps."""
    return hashlib.sha256(spki_der).hexdigest()[:16]


def derive_x25519_public_spki_der(private_scalar: bytes) -> bytes:
    """SPKI DER of the X25519 public key for a raw 32-byte private scalar.
    Deterministic — the ceremony's commitment check hangs off this."""
    _require_cryptography()
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import x25519
    if len(private_scalar) != 32:
        raise ThresholdSealError(
            f"X25519 private scalar must be 32 bytes (got {len(private_scalar)})")
    priv = x25519.X25519PrivateKey.from_private_bytes(private_scalar)
    return priv.public_key().public_bytes(
        serialization.Encoding.DER,
        serialization.PublicFormat.SubjectPublicKeyInfo)


def _load_spki_der(public_key) -> bytes:
    """Accept the encodings seal.mjs accepts: SPKI DER bytes, base64 DER,
    PEM, or a keygen JSON dict/{path} with publicKeyDerB64."""
    if isinstance(public_key, bytes):
        return public_key
    if isinstance(public_key, dict):
        b64 = public_key.get("publicKeyDerB64")
        if not b64:
            raise ThresholdSealError(
                "key JSON has no publicKeyDerB64 — not a public-key file")
        return base64.b64decode(b64)
    raw = str(public_key or "").strip()
    if not raw:
        raise ThresholdSealError("A threshold public key is required.")
    if "-----BEGIN" in raw:
        _require_cryptography()
        from cryptography.hazmat.primitives import serialization
        key = serialization.load_pem_public_key(raw.encode("utf-8"))
        return key.public_bytes(
            serialization.Encoding.DER,
            serialization.PublicFormat.SubjectPublicKeyInfo)
    try:
        der = base64.b64decode(raw, validate=True)
    except Exception as exc:
        raise ThresholdSealError(
            "Threshold public key must be SPKI DER bytes, base64 DER, PEM, "
            "or a keygen JSON with publicKeyDerB64.") from exc
    return der


def _x25519_public_from_spki(spki_der: bytes):
    from cryptography.hazmat.primitives import serialization
    key = serialization.load_der_public_key(spki_der)
    from cryptography.hazmat.primitives.asymmetric import x25519
    if not isinstance(key, x25519.X25519PublicKey):
        raise ThresholdSealError(
            "Threshold public key must be X25519 (sealed-corpus recipient).")
    return key


def _hkdf_aes_key(shared_secret: bytes, salt: bytes, ephemeral_pub_der: bytes,
                  recipient_der: bytes, aad: str) -> bytes:
    """HKDF-SHA256 with the exact seal.mjs info binding: prefix || ephemeral
    SPKI || recipient SPKI || AAD."""
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.kdf.hkdf import HKDF
    info = (_HKDF_INFO_PREFIX + ephemeral_pub_der + recipient_der
            + aad.encode("utf-8"))
    return HKDF(algorithm=hashes.SHA256(), length=_AES_KEY_BYTES,
                salt=salt, info=info).derive(shared_secret)


# ---------------------------------------------------------------------------
# Seal (author side) — mirrors seal.mjs sealPlaintext.
# ---------------------------------------------------------------------------

def seal_bytes(plaintext: bytes, public_key, aad: str) -> dict:
    """Encrypt ``plaintext`` to the threshold public key; return the
    content-free envelope dict (identical shape to seal.mjs sealPlaintext)."""
    _require_cryptography()
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import x25519
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    if not plaintext:
        raise ThresholdSealError("Nothing to seal — plaintext is empty.")
    if not isinstance(aad, str) or not aad:
        raise ThresholdSealError(
            "A binding AAD string is required (see build_aad).")

    recipient_der = _load_spki_der(public_key)
    recipient = _x25519_public_from_spki(recipient_der)

    ephemeral = x25519.X25519PrivateKey.generate()
    shared = ephemeral.exchange(recipient)
    ephemeral_pub_der = ephemeral.public_key().public_bytes(
        serialization.Encoding.DER,
        serialization.PublicFormat.SubjectPublicKeyInfo)
    salt = os.urandom(_HKDF_SALT_BYTES)
    aes_key = _hkdf_aes_key(shared, salt, ephemeral_pub_der, recipient_der, aad)

    iv = os.urandom(_GCM_IV_BYTES)
    ct_and_tag = AESGCM(aes_key).encrypt(iv, plaintext, aad.encode("utf-8"))
    ciphertext, auth_tag = ct_and_tag[:-_GCM_TAG_BYTES], ct_and_tag[-_GCM_TAG_BYTES:]

    return {
        "cipher": SEAL_CIPHER,
        "version": SEAL_VERSION,
        "aad": aad,
        "thresholdKeyId": key_id_for_spki_der(recipient_der),
        "envelope": {
            "ephemeralPublicKey": base64.b64encode(ephemeral_pub_der).decode(),
            "salt": base64.b64encode(salt).decode(),
            "iv": base64.b64encode(iv).decode(),
            "authTag": base64.b64encode(auth_tag).decode(),
        },
        "ciphertext": base64.b64encode(ciphertext).decode(),
        "ciphertextDigest": hashlib.sha256(ciphertext).hexdigest(),
    }


def build_sealed_artifact(sealed: dict, *, card_id: str,
                          custodian_group_id: str,
                          created_at: str | None = None) -> dict:
    """The full ciphertext-only artifact (seal.mjs buildSealedArtifact)."""
    return {
        "champollionSealed": SEAL_VERSION,
        "cardId": card_id,
        "custodianGroupId": custodian_group_id,
        "cipher": sealed["cipher"],
        "aad": sealed["aad"],
        "thresholdKeyId": sealed["thresholdKeyId"],
        "envelope": sealed["envelope"],
        "ciphertext": sealed["ciphertext"],
        "ciphertextDigest": sealed["ciphertextDigest"],
        "createdAt": created_at,
        "_note": (
            "Ciphertext-only sealed corpus. Decryptable ONLY by the custodian "
            "group's threshold key (M-of-N Shamir shares in the ceremony "
            "lane). Champollion holds zero shares and cannot decrypt this. "
            "Never tracked in git or hosted in plaintext."),
    }


def build_sealed_card_block(sealed: dict, *, custodian_group_id: str,
                            key_scheme: str | None = None,
                            qualifier_id: str | None = None,
                            qualifier_threshold: float | None = None,
                            artifact_ref: str | None = None) -> dict:
    """The content-free `sealed` block for the corpus card — the exact field
    set of corpora-card.schema.json#sealed (seal.mjs buildSealedCardBlock)."""
    return {
        "cipher": sealed["cipher"],
        "custodianGroupId": custodian_group_id,
        "ciphertextDigest": sealed["ciphertextDigest"],
        "aad": sealed["aad"],
        "thresholdKeyId": sealed["thresholdKeyId"],
        "keyScheme": key_scheme,
        "qualifierId": qualifier_id,
        "qualifierThreshold": qualifier_threshold,
        "artifactRef": artifact_ref,
    }


# ---------------------------------------------------------------------------
# Open (executor side) — mirrors seal.mjs openSealed, but the private half is
# a RAW 32-byte scalar held in a SecretBuffer, never a key file.
# ---------------------------------------------------------------------------

def open_sealed(artifact: dict, private_scalar: bytes,
                aad: str | None = None) -> bytes:
    """Decrypt a sealed artifact with the raw X25519 private scalar.

    Verifies the ciphertext digest and the GCM tag (which authenticates the
    AAD card binding). The caller owns the scalar's lifetime — pass
    ``SecretBuffer.bytes()`` and close the buffer immediately after."""
    _require_cryptography()
    from cryptography.hazmat.primitives.asymmetric import x25519
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    from cryptography.exceptions import InvalidTag

    if not isinstance(artifact, dict) or "envelope" not in artifact:
        raise ThresholdSealError("Not a sealed artifact (missing envelope).")
    cipher = artifact.get("cipher")
    if cipher != SEAL_CIPHER:
        raise ThresholdSealError(
            f"Unknown sealed-artifact cipher {cipher!r} — this build opens "
            f"only {SEAL_CIPHER!r} (seal.mjs format v{SEAL_VERSION}).")
    expect_aad = aad if aad is not None else artifact.get("aad")
    if not isinstance(expect_aad, str) or not expect_aad:
        raise ThresholdSealError(
            "A binding AAD is required to open a sealed artifact.")

    ciphertext = base64.b64decode(artifact["ciphertext"])
    digest = hashlib.sha256(ciphertext).hexdigest()
    if artifact.get("ciphertextDigest") and digest != artifact["ciphertextDigest"]:
        raise ThresholdSealError(
            "Sealed artifact failed integrity check (ciphertext digest "
            "mismatch).")

    envelope = artifact["envelope"]
    ephemeral_pub_der = base64.b64decode(envelope["ephemeralPublicKey"])
    priv = x25519.X25519PrivateKey.from_private_bytes(private_scalar)
    shared = priv.exchange(_x25519_public_from_spki(ephemeral_pub_der))
    recipient_der = derive_x25519_public_spki_der(private_scalar)
    aes_key = _hkdf_aes_key(shared, base64.b64decode(envelope["salt"]),
                            ephemeral_pub_der, recipient_der, expect_aad)
    try:
        return AESGCM(aes_key).decrypt(
            base64.b64decode(envelope["iv"]),
            ciphertext + base64.b64decode(envelope["authTag"]),
            expect_aad.encode("utf-8"))
    except InvalidTag as exc:
        raise ThresholdSealError(
            "Sealed artifact failed to decrypt: wrong key (quorum "
            "reconstructed a different secret than this artifact was sealed "
            "to) or tampered ciphertext/AAD.") from exc


# ---------------------------------------------------------------------------
# Ed25519 signing — mirrors seal.mjs signPayload/verifyPayload + the
# score-sign keygen file shapes, so Python-signed manifests verify with
# `champollion seal-corpus verify` and vice versa.
# ---------------------------------------------------------------------------

def generate_signing_keypair() -> dict:
    """Ed25519 keypair in the seal.mjs shape:
    {publicKeyDerB64, privateKeyDerB64, keyId}."""
    _require_cryptography()
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ed25519
    priv = ed25519.Ed25519PrivateKey.generate()
    pub_der = priv.public_key().public_bytes(
        serialization.Encoding.DER,
        serialization.PublicFormat.SubjectPublicKeyInfo)
    priv_der = priv.private_bytes(
        serialization.Encoding.DER,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption())
    return {
        "publicKeyDerB64": base64.b64encode(pub_der).decode(),
        "privateKeyDerB64": base64.b64encode(priv_der).decode(),
        "keyId": key_id_for_spki_der(pub_der),
    }


def load_key_material(source, *, want: str):
    """Read signing-key material the way seal-corpus.js readKeyMaterial does:
    ``source`` may be a path to a keygen JSON file, a JSON dict, or a base64
    DER string. ``want`` is 'public' or 'private'; a .key.json passed where a
    public key is needed yields its embedded public half."""
    data = source
    if isinstance(source, (str, Path)) and Path(str(source)).expanduser().is_file():
        data = json.loads(Path(str(source)).expanduser().read_text(encoding="utf-8"))
    if isinstance(data, dict):
        field = ("publicKeyDerB64" if want == "public" else "privateKeyDerB64")
        b64 = data.get(field)
        if not b64:
            raise ThresholdSealError(
                f"key file has no {field} — not a usable {want} key source")
        return base64.b64decode(b64)
    raw = str(data or "").strip()
    if not raw:
        raise ThresholdSealError(f"A {want} key is required.")
    return base64.b64decode(raw)


def sign_payload(payload: bytes, private_key_der: bytes) -> dict:
    """Detached Ed25519 signature block over the payload's exact bytes —
    identical shape to seal.mjs signPayload (+ the caller stamps signedAt)."""
    _require_cryptography()
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ed25519
    if not payload:
        raise ThresholdSealError("sign_payload needs a non-empty payload.")
    priv = serialization.load_der_private_key(private_key_der, password=None)
    if not isinstance(priv, ed25519.Ed25519PrivateKey):
        raise ThresholdSealError("Signing key must be Ed25519.")
    pub_der = priv.public_key().public_bytes(
        serialization.Encoding.DER,
        serialization.PublicFormat.SubjectPublicKeyInfo)
    return {
        "scheme": SIGN_SCHEME,
        "keyId": key_id_for_spki_der(pub_der),
        "payloadSha256": hashlib.sha256(payload).hexdigest(),
        "signatureB64": base64.b64encode(priv.sign(payload)).decode(),
    }


def verify_payload(payload: bytes, signature_b64: str,
                   public_key_der: bytes) -> bool:
    """True iff the signature verifies. The CALLER decides what a failure
    means (always a refusal; never a warning)."""
    _require_cryptography()
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ed25519
    pub = serialization.load_der_public_key(public_key_der)
    if not isinstance(pub, ed25519.Ed25519PublicKey):
        raise ThresholdSealError("Verify key must be Ed25519.")
    try:
        pub.verify(base64.b64decode(str(signature_b64)), payload)
        return True
    except InvalidSignature:
        return False


# ---------------------------------------------------------------------------
# File-level sealing (`mt-eval node seal`) — seal a corpus to the ceremony's
# public key; write the artifact + the card `sealed` block, mirroring the
# seal-corpus.js file layout so either CLI produces the same pair of files.
# ---------------------------------------------------------------------------

def seal_corpus_to_artifact(corpus_path: str | Path, public_key_source, *,
                            card_id: str, custodian_group_id: str,
                            out_dir: str | Path,
                            key_scheme: str | None = None,
                            qualifier_id: str | None = None,
                            qualifier_threshold: float | None = None,
                            artifact_ref: str | None = None) -> dict:
    """Seal ``corpus_path`` → ``<card_id>.sealed.json`` (ciphertext-only
    artifact) + ``<card_id>.sealed-block.json`` (the content-free card
    block). The plaintext is read, sealed, and never copied anywhere else —
    the platform stores ciphertext + metadata, nothing more (M1)."""
    from datetime import datetime, timezone
    src = Path(corpus_path).expanduser()
    if not src.is_file():
        raise ThresholdSealError(f"corpus not found: {src}")
    if isinstance(public_key_source, (str, Path)) and \
            Path(str(public_key_source)).expanduser().is_file():
        public_key_source = json.loads(
            Path(str(public_key_source)).expanduser().read_text(
                encoding="utf-8"))
    if isinstance(public_key_source, dict) and "publicKeyDerB64" in public_key_source:
        key_scheme = key_scheme or public_key_source.get("keyScheme")
    aad = build_aad(card_id, custodian_group_id)
    sealed = seal_bytes(src.read_bytes(), public_key_source, aad)
    out = Path(out_dir).expanduser()
    out.mkdir(parents=True, exist_ok=True)
    artifact = build_sealed_artifact(
        sealed, card_id=card_id, custodian_group_id=custodian_group_id,
        created_at=datetime.now(timezone.utc).isoformat())
    block = build_sealed_card_block(
        sealed, custodian_group_id=custodian_group_id,
        key_scheme=key_scheme, qualifier_id=qualifier_id,
        qualifier_threshold=qualifier_threshold, artifact_ref=artifact_ref)
    artifact_path = out / f"{card_id}.sealed.json"
    block_path = out / f"{card_id}.sealed-block.json"
    artifact_path.write_text(json.dumps(artifact, ensure_ascii=False,
                                        indent=2) + "\n", encoding="utf-8")
    block_path.write_text(json.dumps(block, ensure_ascii=False, indent=2)
                          + "\n", encoding="utf-8")
    print(f"  Sealed '{card_id}' for group '{custodian_group_id}' "
          f"(key {sealed['thresholdKeyId']}, "
          f"scheme {key_scheme or 'unspecified'}):")
    print(f"    artifact    {artifact_path}  (ciphertext-only — store "
          f"OFF-git)")
    print(f"    card block  {block_path}  (content-free metadata for the "
          f"corpus card)")
    print(f"    ciphertext sha256 {sealed['ciphertextDigest']}")
    return {"artifact_path": str(artifact_path),
            "block_path": str(block_path), "artifact": artifact,
            "block": block}
